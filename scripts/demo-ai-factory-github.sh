#!/usr/bin/env bash
# Generate and byte-check the AICR Definition's GitHub hosted Run. No provider is contacted.
set -euo pipefail
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$SCRIPT_DIR/.."
# shellcheck source=scripts/_demo-common.sh
source "$SCRIPT_DIR/_demo-common.sh"

WORK=${WORK:-.nkd/demo-ai-factory-github}
DEFINITION=${DEFINITION:-definitions/aicr/definition.yaml}
ENVIRONMENT=${ENVIRONMENT:-definitions/aicr/environment-github.yaml}

usage() {
  cat <<'EOF'
Usage: scripts/demo-ai-factory-github.sh [options]

Validate the public AICR Definition, inspect its Run plan, generate the GitHub
hosted Run, and prove byte-exact regeneration. No GitHub, registry, OIDC, or
signing service is contacted; this is STATIC-UNQUALIFIED generation evidence.

Options:
  --definition PATH   Definition YAML
  --environment PATH  GitHub Environment YAML
  --work DIR          owned generated output root (default: .nkd/demo-ai-factory-github)
  -h, --help          show help
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --definition) [ "$#" -ge 2 ] || demo_die "missing --definition value"; DEFINITION=$2; shift 2 ;;
    --environment) [ "$#" -ge 2 ] || demo_die "missing --environment value"; ENVIRONMENT=$2; shift 2 ;;
    --work) [ "$#" -ge 2 ] || demo_die "missing --work value"; WORK=$2; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) demo_die "unknown option: $1" ;;
  esac
done

case "$WORK" in .nkd/?*) ;; *) demo_die "--work must be a repository-relative child of .nkd" ;; esac
demo_prepare_nkdctl
demo_prepare_work "$WORK" "ai-factory-github" "$(demo_absolute_path .nkd/demo-ai-factory-github)"

demo_section "1/3  Validate Definition and inspect the frozen Run requirements"
"$NKD" definition validate --definition "$DEFINITION"
"$NKD" run plan --definition "$DEFINITION" --environment "$ENVIRONMENT"

demo_section "2/3  Generate the GitHub hosted Run"
"$NKD" run generate --definition "$DEFINITION" --environment "$ENVIRONMENT" --engine github --root "$WORK"

demo_section "3/3  Prove generated bytes are current"
"$NKD" run generate --check --definition "$DEFINITION" --environment "$ENVIRONMENT" --engine github --root "$WORK"
printf '\nGITHUB HOSTED RUN GENERATED — STATIC-UNQUALIFIED\n  output: %s\n' "$WORK"

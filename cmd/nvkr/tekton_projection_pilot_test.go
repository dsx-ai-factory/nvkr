func tektonCLIEnvironment(t *testing.T, root string) string {
	t.Helper()
	env, err := definition.LoadEnvironment(t.Context(), "docs/examples/nvke-tutorial/environment-github.yaml")
	if err != nil {
		t.Fatal(err)
	}
	server := httptest.NewTLSServer(nil)
	defer server.Close()
	key := func() string {
		private, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			t.Fatal(err)
		}
		der, err := x509.MarshalPKIXPublicKey(&private.PublicKey)
		if err != nil {
			t.Fatal(err)
		}
		return string(pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der}))
	}
	env.RunsOn = ""
	env.Publication.Mode, env.Publication.CredentialRef, env.Publication.Anonymous = "per-output-v1", "", true
	env.Tekton = &definition.TektonExecution{Namespace: "nvkr", Platform: "linux/amd64",
		APIServer: "https://kubernetes.default.svc", CertificateAuthority: string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: server.Certificate().Raw})),
		RunnerImage: env.UtilityContainer, RuntimeImage: env.UtilityContainer, StorageClass: "standard", WorkspaceGiB: 20,
		PublisherPublicKey: key(), QualifierPublicKey: key(), SmokePublicKey: key(),
		Smoke: qualificationpolicy.Smoke{Images: map[string]string{"linux/amd64": "index.docker.io/library/" + env.UtilityContainer}, Tools: map[string]string{"nvkectl": "nvkectl-version-json"},
			NonToolOutputs: []qualificationpolicy.NonToolOutput{{Output: "cwe", Kind: "oci", Components: []string{"cwe"}, Reason: "deployment-image"}}}}
	env.Signing.Issuer = env.Tekton.APIServer
	env.Signing.Identity = "^" + regexp.QuoteMeta(env.Tekton.APIServer+"/api/v1/namespaces/nvkr/serviceaccounts/nvkr-publisher") + "$"
	raw, err := canonical.Marshal(env)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "environment.json")
	if err := os.WriteFile(path, raw, 0o600); err != nil {
		t.Fatal(err)
	}
	return "environment.json"
}

func TestTektonCLIProjectionPilotAndGeneratedCommands(t *testing.T) {
	lifecycleCommandRepo(t)
	t.Setenv("NVKR_WORK_DEADLINE", "")
	root := t.TempDir()
	environment := tektonCLIEnvironment(t, root)
	for _, directory := range []string{"docs/examples/nvke-tutorial", "inputs/catalogs/nvke/module-tags", "inputs/catalogs/shared"} {
		if err := os.CopyFS(filepath.Join(root, directory), os.DirFS(directory)); err != nil {
			t.Fatal(err)
		}
	}
	t.Chdir(root)
	generate := []string{"run", "generate", "--engine", "tekton", "--definition", "docs/examples/nvke-tutorial/definition.yaml", "--environment", environment}
	baseline := t.TempDir()
	if _, err := invokeLifecycleCLI(t, append(generate, "--root", baseline)...); err != nil {
		t.Fatal(err)
	}
	want := generatedTree(t, baseline)
	for _, transport := range []string{"in-process", "out-of-process"} {
		t.Run(transport, func(t *testing.T) {
			root := t.TempDir()
			for _, check := range []bool{false, true} {
				args := append(append([]string{}, generate...), "--root", root, "--projection-pilot="+transport)
				if check {
					args = append(args, "--check")
				}
				if _, err := invokeLifecycleCLI(t, args...); err != nil {
					t.Fatal(err)
				}
			}
			if got := generatedTree(t, root); !reflect.DeepEqual(got, want) {
				t.Fatal("Tekton CLI pilot changed generated bytes")
			}
		})
	}
	// Parse the actual generated invocation for every task, including finally.
	// Cancellation reaches the runtime owner after CLI parsing and before I/O.
	// A leaked selection and a selector trap prove these commands do not select
	// the generation plugin. Factory tests additionally trap its launch seam.
	previous := selectProjectionPilot
	selectProjectionPilot = func(context.Context, string, string) (context.Context, error) {
		t.Error("generated task selected a projection plugin")
		return nil, e.New(e.CodeInternal, "generated task reached projection selection")
	}
	t.Cleanup(func() { selectProjectionPilot = previous })
	var resources struct {
		Items []struct {
			Kind string
			Spec struct {
				PipelineSpec struct {
					Tasks, Finally []struct {
						Name     string
						TaskSpec struct {
							Steps []struct{ Command, Args []string }
						}
					}
				}
			}
		}
	}
	if err := json.Unmarshal([]byte(want[filepath.Join(".tekton", "nvkr-run", "resources.json")]), &resources); err != nil {
		t.Fatal(err)
	}
	seen := map[string]bool{}
	for _, item := range resources.Items {
		if item.Kind != "PipelineRun" {
			continue
		}
		for _, task := range append(item.Spec.PipelineSpec.Tasks, item.Spec.PipelineSpec.Finally...) {
			if len(task.TaskSpec.Steps) != 1 {
				t.Fatal("generated task bypasses the single runner")
			}
			step := task.TaskSpec.Steps[0]
			if !reflect.DeepEqual(step.Command, []string{"/usr/local/bin/nvkr"}) || len(step.Args) < 3 || step.Args[0] != "factory" || step.Args[1] != "tekton" {
				t.Fatalf("unexpected generated invocation: %v %v", step.Command, step.Args)
			}
			for _, arg := range step.Args {
				if strings.Contains(arg, "projection-") {
					t.Fatalf("generated invocation selects a projection: %v", step.Args)
				}
			}
			seen[step.Args[2]] = true
			ctx, cancel := context.WithCancel(factory.WithProjectionAdapter(t.Context(), factory.ProjectionAdapter{
				Transport: factory.ProjectionOutOfProcess, Path: "/nonexistent/projection-adapter", Release: "trap"}))
			cancel()
			app := newApp()
			app.Writer, app.ErrWriter = io.Discard, io.Discard
			err := app.RunContext(ctx, append([]string{"nvkr"}, step.Args...))
			assertLifecycleCommandCode(t, err, e.CodeTimeout)
			if !strings.Contains(err.Error(), "execution projection canceled") {
				t.Fatalf("generated command did not reach the task admission owner: %v", err)
			}
		}
	}
	for _, operation := range []string{"prepare", "execute", "smoke", "qualify", "finalize"} {
		if !seen[operation] {
			t.Errorf("generated tasks did not exercise %s", operation)
		}
	}
}

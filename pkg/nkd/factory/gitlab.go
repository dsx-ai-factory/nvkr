package factory

import (
	"bytes"
	"context"
	"fmt"
	"path/filepath"
	"sort"
	"strings"

	e "github.com/NVIDIA/nke-recipes/pkg/nkd/errors"
)

const (
	GitLabWorkflowPath   = ".gitlab/nkd-factory.yml"
	GitLabManifestPath   = ".gitlab/nkd-factory/manifest.json"
	GitLabPlanPath       = ".gitlab/nkd-factory/plan.json"
	GitLabGraphDir       = ".gitlab/nkd-factory/graphs"
	GitLabCompositionDir = ".gitlab/nkd-factory/compositions"
)

var gitlabLayout = generationLayout{workflowPath: GitLabWorkflowPath,
	manifestPath: GitLabManifestPath, planPath: GitLabPlanPath,
	graphDir: GitLabGraphDir, compositionDir: GitLabCompositionDir}

// RenderGitLab lowers the factory artifact graph to a GitLab DAG include. It uses
// explicit per-edge carrier artifacts and runner tags; it never contacts GitLab.
func RenderGitLab(ctx context.Context, plan *Plan) (*GeneratedBundle, error) {
	if ctx == nil {
		return nil, e.New(e.CodeUsage, "GitLab factory rendering requires a context")
	}
	if plan == nil {
		return nil, e.New(e.CodeInvalidCatalog, "GitLab factory rendering requires a plan")
	}
	if err := plan.Validate(); err != nil {
		return nil, err
	}
	if err := rejectUnsupportedPlanRequirements(plan, "GitLab generation"); err != nil {
		return nil, err
	}
	if len(plan.ExecutionSettings.SourceAccess) != 0 {
		return nil, e.New(e.CodeEngineCapability,
			"GitLab generation does not support Environment.sourceAccess authentication")
	}
	if plan.DefinitionPath == "" || plan.EnvironmentPath == "" {
		return nil, e.New(e.CodeEngineCapability, "GitLab generation requires repository-relative definition and delivery source paths")
	}
	if err := gitlabSigningUnsupported(plan); err != nil {
		return nil, err
	}
	linkerFlags, err := generatorLinkerFlags(plan.GeneratorVersion)
	if err != nil {
		return nil, err
	}
	files, planDigest, graphDigests, err := renderStaticInputs(ctx, plan, gitlabLayout)
	if err != nil {
		return nil, err
	}
	artifacts := make(map[string]Artifact, len(plan.Graph.Artifacts))
	for _, artifact := range plan.Graph.Artifacts {
		artifacts[artifact.ID] = artifact
	}
	nodeJobs := make(map[string]string, len(plan.Graph.Nodes))
	bootstrapJobs := map[string]string{}
	for _, node := range plan.Graph.Nodes {
		nodeJobs[node.ID] = generatedJobID(node.ID)
		bootstrapJobs[node.RunsOn] = "build-runner-" + shortStableName(node.RunsOn)
	}
	depths, maxDepth, err := factoryNodeDepths(plan.Graph)
	if err != nil {
		return nil, err
	}

	var body bytes.Buffer
	fmt.Fprintln(&body, "# GENERATED BY nkdctl run generate — DO NOT EDIT")
	fmt.Fprintf(&body, "# planDigest: %s\n", planDigest)
	fmt.Fprintf(&body, "# qualification: %s (runtime receipts are not fabricated)\n", plan.Qualification)
	fmt.Fprintln(&body, "workflow:")
	fmt.Fprintln(&body, "  rules:")
	fmt.Fprintln(&body, "    - if: '$CI_PIPELINE_SOURCE == \"merge_request_event\"'")
	fmt.Fprintln(&body, "    - if: '$CI_PIPELINE_SOURCE == \"web\"'")
	fmt.Fprint(&body, "stages: [bootstrap")
	for depth := 1; depth <= maxDepth; depth++ {
		fmt.Fprintf(&body, ", factory-%03d", depth)
	}
	if plan.DefinitionDigest != "" && plan.EnvironmentDigest != "" {
		fmt.Fprint(&body, ", lifecycle-status, lifecycle")
	}
	fmt.Fprintln(&body, "]")
	fmt.Fprintln(&body)
	for _, runner := range sortedKeys(bootstrapJobs) {
		jobID := bootstrapJobs[runner]
		fmt.Fprintf(&body, "%s:\n", jobID)
		fmt.Fprintln(&body, "  stage: bootstrap")
		// The from-source bootstrap needs the Go toolchain. GitLab has no setup-go action and a
		// bare docker/dind runner has no Go, so run it on the operator's pinned builder image.
		if img := strings.TrimSpace(plan.ExecutionSettings.Runtime.BuilderImage); img != "" {
			fmt.Fprintf(&body, "  image: %s\n", yamlSingle(img))
		}
		fmt.Fprintf(&body, "  tags: [%s]\n", yamlSingle(runner))
		fmt.Fprintln(&body, "  script:")
		fmt.Fprintf(&body, "    - CGO_ENABLED=0 go build -trimpath -ldflags %s -o nkd-exec ./cmd/nkdctl\n", shellQuote(linkerFlags))
		fmt.Fprintf(&body, "    - %s\n", generationCommand(plan, EngineGitLab))
		fmt.Fprintln(&body, "  artifacts:")
		fmt.Fprintln(&body, "    paths: [nkd-exec]")
		fmt.Fprintln(&body)
	}
	for _, node := range plan.Graph.Nodes {
		if err := ctx.Err(); err != nil {
			return nil, e.Wrap(e.CodeTimeout, err, "GitLab factory rendering canceled")
		}
		jobID := nodeJobs[node.ID]
		needs := []string{bootstrapJobs[node.RunsOn]}
		for _, input := range node.Inputs {
			needs = append(needs, nodeJobs[artifacts[input].Producer])
		}
		needs = uniqueSorted(needs)
		fmt.Fprintf(&body, "%s:\n", jobID)
		fmt.Fprintf(&body, "  stage: factory-%03d\n", depths[node.ID])
		// Node jobs run the transported nkd-exec (a static binary) and orchestrate the pinned
		// toolchain container via `docker run`, so they run on the operator's pinned runtime
		// image (a docker-capable base). Empty leaves them on the runner's default image.
		if img := strings.TrimSpace(plan.ExecutionSettings.Runtime.RuntimeImage); img != "" {
			fmt.Fprintf(&body, "  image: %s\n", yamlSingle(img))
		}
		// ADR-18 §8: for an IR-projected node the helper self-orchestrates its pinned
		// container via `nkd-exec exec-node --launch` (verified below); glue nodes still use an
		// inline `<runtime> run --network none` wrapper. Either way no bespoke network-none
		// runner tag is emitted — only the operator's own RunsOn runner selection.
		tags := []string{node.RunsOn}
		sort.Strings(tags)
		fmt.Fprintf(&body, "  tags: [%s]\n", yamlQuotedList(tags))
		fmt.Fprintf(&body, "  needs: [%s]\n", strings.Join(needs, ", "))
		if node.Kind == NodeVerify {
			fmt.Fprintln(&body, "  when: always")
		}
		// Environment config (ADR-18 §8): the operator's job variables (e.g. DOCKER_HOST for a dind
		// daemon) plus, for a publish node only, its credential reference — merged into ONE
		// variables block. A build-only delivery has no publish node and no credential.
		vars := map[string]string{}
		for k, v := range plan.ExecutionSettings.Runtime.Variables {
			vars[k] = v
		}
		if node.Kind == NodePublish {
			target := plan.ExecutionSettings.Targets[node.Target]
			if target.CredentialRef != "" {
				secret, ok := strings.CutPrefix(target.CredentialRef, "gitlab:")
				if !ok || !regexpSecret(secret) {
					return nil, e.New(e.CodeInvalidCatalog,
						"GitLab target %q credentialRef must be gitlab:VARIABLE_NAME", node.Target)
				}
				vars["NKD_CREDENTIAL"] = "$" + secret
				vars["NKD_REGISTRY_USER"] = "$CI_REGISTRY_USER"
			}
		}
		if len(vars) > 0 {
			fmt.Fprintln(&body, "  variables:")
			for _, k := range sortedKeys(vars) {
				fmt.Fprintf(&body, "    %s: %s\n", k, yamlSingle(vars[k]))
			}
		}
		// The helper's `docker run` needs a daemon; attach the operator's pinned dind service(s).
		if svcs := plan.ExecutionSettings.Runtime.Services; len(svcs) > 0 {
			fmt.Fprintf(&body, "  services: [%s]\n", yamlQuotedList(svcs))
		}
		// Operator setup before the helper runs (e.g. `docker login` so the dind daemon can pull
		// a private, digest-pinned toolchain from the operator registry). Environment config.
		if setup := plan.ExecutionSettings.Runtime.Setup; len(setup) > 0 {
			fmt.Fprintln(&body, "  before_script:")
			for _, line := range setup {
				fmt.Fprintf(&body, "    - %s\n", yamlSingle(line))
			}
		}
		fmt.Fprintln(&body, "  script:")
		fmt.Fprintln(&body, "    - |")
		fmt.Fprintln(&body, "      set -eu")
		fmt.Fprintln(&body, "      chmod +x ./nkd-exec")
		for _, input := range node.Inputs {
			fmt.Fprintf(&body, "      ./nkd-exec transport-unpack --archive %s --root . --path %s\n",
				shellQuote(carrierPath(input)), shellQuote(artifacts[input].Path))
		}
		for _, line := range generatedNodeCommands(node, plan, graphDigests,
			GitLabPlanPath, GitLabGraphDir, "$CI_PROJECT_DIR") {
			fmt.Fprintf(&body, "      %s\n", line)
		}
		for _, output := range node.Outputs {
			fmt.Fprintf(&body, "      ./nkd-exec transport-pack --archive %s --root . --path %s\n",
				shellQuote(carrierPath(output)), shellQuote(artifacts[output].Path))
		}
		if len(node.Outputs) > 0 {
			fmt.Fprintln(&body, "  artifacts:")
			fmt.Fprintln(&body, "    paths:")
			for _, output := range node.Outputs {
				fmt.Fprintf(&body, "      - %s\n", yamlSingle(carrierPath(output)))
			}
		}
		fmt.Fprintln(&body)
	}
	if plan.DefinitionDigest != "" && plan.EnvironmentDigest != "" {
		providerSuccess := ".nkd/provider-outcomes/all-jobs-success"
		producerNeeds := make([]string, 0, len(nodeJobs))
		for _, job := range nodeJobs {
			producerNeeds = append(producerNeeds, job)
		}
		producerNeeds = uniqueSorted(producerNeeds)
		fmt.Fprintln(&body, "nkd-lifecycle-jobs-succeeded:")
		fmt.Fprintln(&body, "  stage: lifecycle-status")
		fmt.Fprintf(&body, "  tags: [%s]\n", yamlSingle(sortedKeys(bootstrapJobs)[0]))
		fmt.Fprintf(&body, "  needs: [%s]\n", strings.Join(producerNeeds, ", "))
		fmt.Fprintln(&body, "  script:")
		fmt.Fprintf(&body, "    - mkdir -p %s && printf 'success\\n' > %s\n", shellQuote(filepath.Dir(providerSuccess)), shellQuote(providerSuccess))
		fmt.Fprintln(&body, "  artifacts:")
		fmt.Fprintf(&body, "    paths: [%s]\n", providerSuccess)
		fmt.Fprintln(&body)
		allNeeds := make([]string, 0, len(nodeJobs)+len(bootstrapJobs))
		for _, job := range nodeJobs {
			allNeeds = append(allNeeds, job)
		}
		for _, job := range bootstrapJobs {
			allNeeds = append(allNeeds, job)
		}
		allNeeds = append(allNeeds, "nkd-lifecycle-jobs-succeeded")
		allNeeds = uniqueSorted(allNeeds)
		runners := sortedKeys(bootstrapJobs)
		fmt.Fprintln(&body, "nkd-lifecycle-run:")
		fmt.Fprintln(&body, "  stage: lifecycle")
		if img := strings.TrimSpace(plan.ExecutionSettings.Runtime.BuilderImage); img != "" {
			fmt.Fprintf(&body, "  image: %s\n", yamlSingle(img))
		}
		fmt.Fprintf(&body, "  tags: [%s]\n", yamlSingle(runners[0]))
		fmt.Fprintf(&body, "  needs: [%s]\n", strings.Join(allNeeds, ", "))
		fmt.Fprintln(&body, "  when: always")
		fmt.Fprintln(&body, "  script:")
		fmt.Fprintf(&body, "    - if [ ! -x ./nkd-exec ]; then CGO_ENABLED=0 go build -trimpath -ldflags %s -o nkd-exec ./cmd/nkdctl; fi\n", shellQuote(linkerFlags))
		fmt.Fprintln(&body, "    - chmod +x ./nkd-exec")
		fmt.Fprintln(&body, "    - mkdir -p .nkd/restore-outcomes")
		for _, artifact := range plan.Graph.Artifacts {
			status := filepath.ToSlash(HostedRestoreOutcomePath(".nkd/factory", artifact.ID))
			fmt.Fprintf(&body, "    - if [ ! -f %s ]; then printf 'job-failed\\n' > %s; elif [ ! -f %s ]; then printf 'missing\\n' > %s; elif ./nkd-exec transport-unpack --archive %s --root . --path %s; then printf 'restored:success\\n' > %s; else printf 'restore-failed\\n' > %s; fi\n",
				shellQuote(providerSuccess), shellQuote(status), shellQuote(carrierPath(artifact.ID)), shellQuote(status), shellQuote(carrierPath(artifact.ID)), shellQuote(artifact.Path), shellQuote(status), shellQuote(status))
		}
		fmt.Fprintf(&body, "    - ./nkd-exec run finalize --definition %s --environment %s --plan %s --attempt \"${CI_PIPELINE_ID}-${CI_JOB_ID}\" --workspace .nkd/factory --out .nkd/run.json\n",
			shellQuote(plan.DefinitionPath), shellQuote(plan.EnvironmentPath), shellQuote(GitLabPlanPath))
		fmt.Fprintln(&body, "  artifacts:")
		fmt.Fprintln(&body, "    when: always")
		fmt.Fprintln(&body, "    paths: [.nkd/run.json]")
	}
	files[GitLabWorkflowPath] = append([]byte(nil), body.Bytes()...)
	bundle := newGeneratedBundle(EngineGitLab, gitlabLayout, files, planDigest)
	if err := ValidateGitLabBundle(ctx, plan, bundle); err != nil {
		return nil, err
	}
	return bundle, nil
}

// gitlabSigningUnsupported refuses a signing plan BEFORE any bytes are produced.
// The GitLab lane has no authenticated identity model here — no rendered OIDC
// identity token, no per-job scope narrowing, and therefore nothing a verifier
// could pin a certificate identity to. Silently rendering the pipeline without
// its sign and verify-publication jobs would emit a pipeline that publishes
// unsigned artifacts while its plan claims signing was configured, so this fails
// closed instead.
func gitlabSigningUnsupported(plan *Plan) error {
	if plan.ExecutionSettings.Signing == nil {
		return nil
	}
	return e.New(e.CodeEngineCapability,
		"GitLab generation cannot enforce publication signing (delivery signing mode %q); "+
			"no signing/verification adapter is implemented for this engine", plan.ExecutionSettings.Signing.Mode)
}

func factoryNodeDepths(graph ArtifactGraph) (map[string]int, int, error) {
	artifacts := make(map[string]Artifact, len(graph.Artifacts))
	nodes := make(map[string]Node, len(graph.Nodes))
	for _, artifact := range graph.Artifacts {
		artifacts[artifact.ID] = artifact
	}
	for _, node := range graph.Nodes {
		nodes[node.ID] = node
	}
	depths := make(map[string]int, len(nodes))
	visiting := make(map[string]bool, len(nodes))
	var visit func(string) (int, error)
	visit = func(id string) (int, error) {
		if depth := depths[id]; depth != 0 {
			return depth, nil
		}
		if visiting[id] {
			return 0, e.New(e.CodeInvalidCatalog, "factory graph contains a cycle at %q", id)
		}
		visiting[id] = true
		depth := 1
		for _, input := range nodes[id].Inputs {
			producerDepth, err := visit(artifacts[input].Producer)
			if err != nil {
				return 0, err
			}
			if producerDepth+1 > depth {
				depth = producerDepth + 1
			}
		}
		visiting[id] = false
		depths[id] = depth
		return depth, nil
	}
	maxDepth := 0
	for id := range nodes {
		depth, err := visit(id)
		if err != nil {
			return nil, 0, err
		}
		if depth > maxDepth {
			maxDepth = depth
		}
	}
	return depths, maxDepth, nil
}

func generatedJobID(id string) string { return "nkd-" + shortStableName(id) }

func yamlQuotedList(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = yamlSingle(value)
	}
	return strings.Join(quoted, ", ")
}

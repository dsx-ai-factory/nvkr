const (
	GitHubWorkflowPath       = ".github/workflows/nkd-run.yml"
	FactoryPlanPath          = ".github/nkd-run/plan.json"
	FactoryGraphDir          = ".github/nkd-run/graphs"
	FactoryCompositionDir    = ".github/nkd-run/compositions"
	githubExecutionCondition = "github.event_name == 'workflow_dispatch' && github.ref == format('refs/heads/{0}', github.event.repository.default_branch)"
)

// The pinned GitHub Action references are aliased from the authoritative pipeline adapter so
// both GitHub emitters share ONE definition (the embedded actions.lock.yaml) and a security
// bump — `nkdctl actions bump` — is made in exactly one place. They are vars, not consts,
// because they are sourced from that lockfile at load time rather than baked in as literals.
var (
	githubCheckoutAction = pipeline.GitHubCheckoutAction
	githubUploadAction   = pipeline.GitHubUploadAction
	githubDownloadAction = pipeline.GitHubDownloadAction
	githubSetupGoAction  = pipeline.GitHubSetupGoAction
)

var githubLayout = generationLayout{workflowPath: GitHubWorkflowPath,
	manifestPath: GeneratedManifestPath, planPath: FactoryPlanPath,
	graphDir: FactoryGraphDir, compositionDir: FactoryCompositionDir}

// RenderGitHub emits a locally inspectable workflow and its exact plan/IR inputs,
// then runs the semantic static validator before returning any bytes.
func RenderGitHub(ctx context.Context, plan *Plan) (*GeneratedBundle, error) {
	if ctx == nil {
		return nil, e.New(e.CodeUsage, "GitHub factory rendering requires a context")
	}
	if plan == nil {
		return nil, e.New(e.CodeInvalidCatalog, "GitHub factory rendering requires a plan")
	}
	if err := plan.Validate(); err != nil {
		return nil, err
	}
	if plan.DefinitionPath == "" || plan.EnvironmentPath == "" {
		return nil, e.New(e.CodeEngineCapability, "GitHub generation requires repository-relative definition and delivery source paths")
	}
	linkerFlags, err := generatorLinkerFlags(plan.GeneratorVersion)
	if err != nil {
		return nil, err
	}
	files, planDigest, graphDigest, err := renderStaticInputs(ctx, plan, githubLayout)
	if err != nil {
		return nil, err
	}

	artifacts := make(map[string]Artifact, len(plan.Graph.Artifacts))
	for _, artifact := range plan.Graph.Artifacts {
		artifacts[artifact.ID] = artifact
	}
	nodeJobs := make(map[string]string, len(plan.Graph.Nodes))
	for _, node := range plan.Graph.Nodes {
		nodeJobs[node.ID] = githubJobID(node.ID)
	}
	bootstrapJobs := map[string]string{}
	for _, node := range plan.Graph.Nodes {
		bootstrapJobs[node.RunsOn] = "build-runner-" + shortStableName(node.RunsOn)
	}

	var body bytes.Buffer
	fmt.Fprintf(&body, "# GENERATED BY nkdctl run generate — DO NOT EDIT\n")
	fmt.Fprintf(&body, "# planDigest: %s\n", planDigest)
	fmt.Fprintf(&body, "# qualification: %s (runtime receipts are not fabricated)\n", plan.Qualification)
	fmt.Fprintf(&body, "name: nkd-run-%s\n", plan.Name)
	fmt.Fprintf(&body, "'on':\n  workflow_dispatch: {}\n  pull_request: {}\n")
	fmt.Fprintf(&body, "permissions:\n  contents: read\n\n")
	fmt.Fprint(&body, "concurrency:\n  group: nkd-run-${{ github.workflow }}-${{ github.ref }}\n  cancel-in-progress: false\n")
	fmt.Fprintf(&body, "jobs:\n")
	for _, runner := range sortedKeys(bootstrapJobs) {
		jobID := bootstrapJobs[runner]
		fmt.Fprintf(&body, "  %s:\n", jobID)
		fmt.Fprintf(&body, "    name: Build static NKD runner (%s)\n", yamlSingle(runner))
		fmt.Fprintf(&body, "    runs-on: %s\n", yamlSingle(runner))
		fmt.Fprintln(&body, "    timeout-minutes: 15")
		fmt.Fprintf(&body, "    steps:\n")
		writeCheckoutStep(&body)
		writeSetupGoStep(&body)
		fmt.Fprintf(&body, "      - name: Build runner from this checkout\n        run: CGO_ENABLED=0 go build -trimpath -ldflags %s -o nkd-exec ./cmd/nkdctl\n", shellQuote(linkerFlags))
		fmt.Fprintf(&body, "      - name: Verify committed Run generation is current\n        run: %s\n",
			generationCommand(plan, EngineGitHub))
		writeUploadStep(&body, "nkd-exec-"+shortStableName(runner), "nkd-exec")
	}
	for _, node := range plan.Graph.Nodes {
		if err := ctx.Err(); err != nil {
			return nil, e.Wrap(e.CodeTimeout, err, "GitHub factory rendering canceled")
		}
		jobID := nodeJobs[node.ID]
		needs := []string{bootstrapJobs[node.RunsOn]}
		for _, input := range node.Inputs {
			needs = append(needs, nodeJobs[artifacts[input].Producer])
		}
		needs = uniqueSorted(needs)
		fmt.Fprintf(&body, "  %s:\n", jobID)
		fmt.Fprintf(&body, "    name: %s\n", yamlSingle(node.ID))
		fmt.Fprintf(&body, "    runs-on: %s\n", yamlSingle(node.RunsOn))
		fmt.Fprintln(&body, "    timeout-minutes: 60")
		// Engine-agnostic environment config (ADR-18 §8), rendered in GitHub syntax: a docker-capable
		// job container, dind service containers, and job env — for a runner that lacks them
		// natively. (BuilderImage stays GitLab-only: GitHub provisions Go via setup-go.)
		if img := strings.TrimSpace(plan.ExecutionSettings.Runtime.RuntimeImage); img != "" {
			fmt.Fprintf(&body, "    container: %s\n", yamlSingle(img))
		}
		if svcs := plan.ExecutionSettings.Runtime.Services; len(svcs) > 0 {
			fmt.Fprintln(&body, "    services:")
			for i, svc := range svcs {
				fmt.Fprintf(&body, "      svc-%02d:\n        image: %s\n", i, yamlSingle(svc))
			}
		}
		fmt.Fprintf(&body, "    needs: [%s]\n", strings.Join(needs, ", "))
		if node.Kind == NodeVerify {
			fmt.Fprintf(&body, "    if: ${{ always() && %s }}\n", githubExecutionCondition)
		} else {
			fmt.Fprintf(&body, "    if: ${{ %s }}\n", githubExecutionCondition)
		}
		env := map[string]string{}
		for k, v := range plan.ExecutionSettings.Runtime.Variables {
			env[k] = v
		}
		if node.Kind == NodePublish {
			target := plan.ExecutionSettings.Targets[node.Target]
			fmt.Fprintf(&body, "    permissions:\n      contents: read\n")
			if target.CredentialRef != "" {
				secret, ok := strings.CutPrefix(target.CredentialRef, "github:")
				if !ok || !regexpSecret(secret) {
					return nil, e.New(e.CodeInvalidCatalog, "GitHub target %q credentialRef must be github:SECRET_NAME", node.Target)
				}
				if strings.HasPrefix(target.Ref, "ghcr.io/") {
					fmt.Fprintf(&body, "      packages: write\n")
				}
				env["NKD_CREDENTIAL"] = "${{ secrets." + secret + " }}"
				env["NKD_REGISTRY_USER"] = "${{ github.actor }}"
			}
		}
		if signFamilyNode(node.Kind) {
			signing := plan.ExecutionSettings.Signing
			if signing == nil {
				return nil, e.New(e.CodeTrustPolicyMissing,
					"GitHub node %q signs without a delivery signing profile", node.ID)
			}
			// Signing scopes are per-mode and per-kind, and `id-token: write` (the OIDC
			// token keyless cosign exchanges for a certificate) is emitted ONLY here.
			permissions := githubSigningPermissions(node.Kind, signing.Mode)
			fmt.Fprintf(&body, "    permissions:\n")
			for _, name := range sortedKeys(permissions) {
				fmt.Fprintf(&body, "      %s: %s\n", name, permissions[name])
			}
			target := plan.ExecutionSettings.Targets[node.Target]
			if target.CredentialRef != "" {
				secret, ok := strings.CutPrefix(target.CredentialRef, "github:")
				if !ok || !regexpSecret(secret) {
					return nil, e.New(e.CodeInvalidCatalog, "GitHub target %q credentialRef must be github:SECRET_NAME", node.Target)
				}
				env["NKD_CREDENTIAL"] = "${{ secrets." + secret + " }}"
				env["NKD_REGISTRY_USER"] = "${{ github.actor }}"
			}
		}
		if len(env) > 0 {
			fmt.Fprintln(&body, "    env:")
			for _, k := range sortedKeys(env) {
				fmt.Fprintf(&body, "      %s: %s\n", k, yamlSingle(env[k]))
			}
		}
		fmt.Fprintf(&body, "    steps:\n")
		writeCheckoutStep(&body)
		writeDownloadStep(&body, "nkd-exec-"+shortStableName(node.RunsOn), ".")
		// upload-artifact/download-artifact do not preserve the execute bit, so the helper
		// arrives non-executable. Restore it in a dedicated step IMMEDIATELY after the helper
		// download, before ANY ./nkd-exec invocation: the input Restore steps below are
		// themselves helper invocations, so a chmod folded into the later Execute step leaves
		// every input-bearing job failing at its first Restore.
		writePrepareHelperStep(&body)
		for _, input := range node.Inputs {
			writeDownloadStep(&body, githubArtifactName(input), ".nkd/carriers")
			fmt.Fprintf(&body, "      - name: Restore %s\n        run: ./nkd-exec transport-unpack --archive %s --root . --path %s\n",
				yamlSingle(input), shellQuote(carrierPath(input)), shellQuote(artifacts[input].Path))
		}
		// Operator setup before the helper runs (e.g. `docker login` to pull a private,
		// digest-pinned toolchain). Same engine-agnostic delivery.runtime.setup as GitLab.
		if setup := plan.ExecutionSettings.Runtime.Setup; len(setup) > 0 {
			fmt.Fprintf(&body, "      - name: Setup\n        run: |\n")
			for _, line := range setup {
				fmt.Fprintf(&body, "          %s\n", line)
			}
		}
		fmt.Fprintf(&body, "      - name: %s\n", yamlSingle("Execute "+node.ID))
		sourceEnv := githubSourceEnvironment(plan, node)
		if len(sourceEnv) > 0 {
			fmt.Fprintln(&body, "        env:")
			for _, key := range sortedKeys(sourceEnv) {
				fmt.Fprintf(&body, "          %s: %s\n", key, yamlSingle(sourceEnv[key]))
			}
		}
		fmt.Fprintln(&body, "        run: |")
		if len(sourceEnv) > 0 {
			fmt.Fprintf(&body, "          %s\n", requireSourceToken)
		}
		for _, line := range generatedNodeCommands(node, plan, graphDigest, FactoryPlanPath, FactoryGraphDir, "$GITHUB_WORKSPACE") {
			fmt.Fprintf(&body, "          %s\n", line)
		}
		for _, output := range node.Outputs {
			fmt.Fprintf(&body, "      - name: Pack %s\n        run: ./nkd-exec transport-pack --archive %s --root . --path %s\n",
				yamlSingle(output), shellQuote(carrierPath(output)), shellQuote(artifacts[output].Path))
			writeUploadStep(&body, githubArtifactName(output), carrierPath(output))
		}
	}
	if plan.DefinitionDigest != "" && plan.EnvironmentDigest != "" {
		allNeeds := make([]string, 0, len(nodeJobs)+len(bootstrapJobs))
		for _, job := range nodeJobs {
			allNeeds = append(allNeeds, job)
		}
		for _, job := range bootstrapJobs {
			allNeeds = append(allNeeds, job)
		}
		allNeeds = uniqueSorted(allNeeds)
		runners := sortedKeys(bootstrapJobs)
		fmt.Fprintln(&body, "  nkd-lifecycle-run:")
		fmt.Fprintln(&body, "    name: Finalize lifecycle Run")
		fmt.Fprintf(&body, "    runs-on: %s\n", yamlSingle(runners[0]))
		fmt.Fprintln(&body, "    timeout-minutes: 15")
		fmt.Fprintf(&body, "    needs: [%s]\n", strings.Join(allNeeds, ", "))
		fmt.Fprintf(&body, "    if: ${{ always() && %s }}\n", githubExecutionCondition)
		fmt.Fprintln(&body, "    steps:")
		writeCheckoutStep(&body)
		writeDownloadStep(&body, "nkd-exec-"+shortStableName(runners[0]), ".")
		writePrepareHelperStep(&body)
		fmt.Fprintln(&body, "      - name: Prepare restore outcomes\n        run: mkdir -p .nkd/restore-outcomes")
		for _, artifact := range plan.Graph.Artifacts {
			fmt.Fprintf(&body, "      - uses: %s\n        continue-on-error: true\n        with:\n          name: %s\n          path: .nkd/carriers\n", githubDownloadAction, yamlSingle(githubArtifactName(artifact.ID)))
			status := filepath.ToSlash(HostedRestoreOutcomePath(".nkd/factory", artifact.ID))
			producerJob := nodeJobs[artifact.Producer]
			fmt.Fprintf(&body, "      - name: Restore %s when produced\n        run: if [ '${{ needs.%s.result }}' != 'success' ]; then printf 'job-failed\\n' > %s; elif [ ! -f %s ]; then printf 'missing\\n' > %s; elif ./nkd-exec transport-unpack --archive %s --root . --path %s; then printf 'restored:success\\n' > %s; else printf 'restore-failed\\n' > %s; fi\n",
				yamlSingle(artifact.ID), producerJob, shellQuote(status), shellQuote(carrierPath(artifact.ID)), shellQuote(status), shellQuote(carrierPath(artifact.ID)), shellQuote(artifact.Path), shellQuote(status), shellQuote(status))
		}
		fmt.Fprintf(&body, "      - name: Finalize lifecycle Run\n        run: ./nkd-exec run finalize --definition %s --environment %s --plan %s --attempt \"${{ github.run_id }}-${{ github.run_attempt }}\" --workspace .nkd/factory --out .nkd/run.json\n",
			shellQuote(plan.DefinitionPath), shellQuote(plan.EnvironmentPath), shellQuote(FactoryPlanPath))
		fmt.Fprintf(&body, "      - uses: %s\n        if: ${{ always() }}\n        with:\n          name: nkd-lifecycle-run\n          path: .nkd/run.json\n          if-no-files-found: error\n", githubUploadAction)
	}
	workflow := body.Bytes()
	files[GitHubWorkflowPath] = append([]byte(nil), workflow...)
	bundle := newGeneratedBundle(EngineGitHub, githubLayout, files, planDigest)
	if err := ValidateGitHubBundle(ctx, plan, bundle); err != nil {
		return nil, err
	}
	return bundle, nil
}

// signFamilyNode reports whether a node kind belongs to the signing family: the
// only jobs permitted to request an OIDC identity token. It is the ONE definition
// the emitter and the validator share, so a job that may hold `id-token: write`
// and a job that does hold it can never diverge.
func signFamilyNode(kind string) bool {
	return kind == NodeSign || kind == NodeVerifyPublication
}

// githubSigningPermissions is the exact token scope set of one signing-family job.
// dry-run signing executes nothing and contacts no registry, so it asks for no
// write scope and no identity token at all; cosign mode needs an OIDC token to
// obtain a short-lived certificate, plus registry write to attach the signature
// (sign) or registry read to fetch it back (verify).
func githubSigningPermissions(kind, mode string) map[string]string {
	permissions := map[string]string{"contents": "read"}
	if kind == NodeVerifyPublication {
		permissions["packages"] = "read"
	}
	if mode != SigningModeCosign {
		return permissions
	}
	permissions["id-token"] = "write"
	if kind == NodeSign {
		permissions["packages"] = "write"
	}
	return permissions
}

// irProjectedNode reports whether a node is a recipe-projected fetch/build/acquire node — one
// backed by a committed per-recipe IR graph, so it carries BOTH a RecipeTarget and an IRNode.
// Such a node runs `nkd-exec exec-node` over that graph. A tool-download acquire node has
// neither and is NOT IR-projected: it has no recipe graph, so it runs through the glue
// `factory execute-node` path instead (routing it to exec-node would reference graphs/.json).
func irProjectedNode(node Node) bool {
	switch node.Kind {
	case NodeFetch, NodeBuild, NodeAcquire:
		return node.RecipeTarget != "" && node.IRNode != ""
	default:
		return false
	}
}

// launchedExecNode reports whether a node is emitted as an ADR-18 §8 `exec-node --launch`
// invocation: an IR-projected node that carries a pinned container the helper must orchestrate
// itself. It is the ONE definition the emitter's Launch decision and the GitHub/GitLab
// validators' isolation checks both consult, so the rendered and accepted topology cannot
// diverge. An acquire/pull node with no container runs the helper directly and is not launched.
func launchedExecNode(node Node) bool {
	return irProjectedNode(node) && node.Container != ""
}

func generatedNodeCommands(node Node, plan *Plan, graphDigests map[string]string, planPath, graphDir, workspaceVariable string) []string {
	// The container runtime the helper orchestrates with is sourced from the operator's
	// Environment execution settings (ADR-18 §8), defaulting to rootless podman.
	runtime := plan.ExecutionSettings.RuntimeBinary()
	if irProjectedNode(node) {
		graphPath := filepath.ToSlash(filepath.Join(graphDir, node.RecipeTarget+".json"))
		sourceRoot := filepath.ToSlash(filepath.Join(".nkd", "factory", node.RecipeTarget, "src"))
		result := ""
		if node.Kind == NodeBuild || node.Kind == NodeAcquire {
			result = filepath.ToSlash(filepath.Join(".nkd", "factory", node.RecipeTarget, "results", node.IRNode+".json"))
		}
		// ADR-18 §8: a containerized IR node (a build toolchain or a fetch vendor image)
		// is isolated by nkd-exec ITSELF orchestrating the pinned container (--launch), which
		// reads that container, its platform, and its --network=none posture from the committed
		// per-recipe graph node (re-checked by the recipeDigest drift gate) — not by an inline
		// `<runtime> run` wrapper in the YAML. This is the SAME per-node primitive the
		// single-recipe pipeline emitter renders, so the two stacks share one topology. An
		// acquire/pull node carries no container and runs the helper directly (Launch=false).
		return []string{pipeline.ExecNodeCommand(pipeline.NodeExec{
			NodeID:      node.IRNode,
			NodesFile:   graphPath,
			NodesDigest: graphDigests[node.RecipeTarget],
			SourceRoot:  sourceRoot,
			Result:      result,
			Launch:      launchedExecNode(node),
			Runtime:     runtime,
		}, pipeline.BootstrapHelperRef())}
	}
	// Glue nodes (package/publish/composition/aicr-render/terminal-observe) AND tool-download
	// acquire nodes with no recipe graph run `factory execute-node` over the committed plan.
	command := fmt.Sprintf("./nkd-exec factory execute-node --plan %s --node %s --workspace .nkd/factory",
		shellQuote(planPath), shellQuote(node.ID))
	if node.Container == "" {
		return []string{command}
	}
	network := "bridge"
	if node.Network == ir.NetworkNone {
		network = "none"
	}
	platform := ""
	if node.Platform != "" {
		platform = " --platform " + shellQuote(node.Platform)
	}
	return []string{fmt.Sprintf("%s run --rm --network %s%s -v \"%s:/workspace\" -w /workspace %s %s",
		runtime, network, platform, workspaceVariable, shellQuote(node.Container), "/workspace/"+strings.TrimPrefix(command, "./"))}
}

func writeUploadStep(out *bytes.Buffer, name, path string) {
	fmt.Fprintf(out, "      - uses: %s\n        with:\n          name: %s\n          path: %s\n          if-no-files-found: error\n", githubUploadAction, yamlSingle(name), yamlSingle(path))
}

func writeCheckoutStep(out *bytes.Buffer) {
	fmt.Fprintf(out, "      - uses: %s\n        with:\n          persist-credentials: 'false'\n", githubCheckoutAction)
}

// writeSetupGoStep provisions the Go toolchain on the runner before the bootstrap `go build`,
// so the workflow does not silently depend on a preinstalled Go (true on GitHub-hosted
// ubuntu-latest, but not on a minimal or self-hosted runner). The version is read from the
// checked-out repo's .go-version, so setup-go and the actual build toolchain cannot drift.
func writeSetupGoStep(out *bytes.Buffer) {
	fmt.Fprintf(out, "      - uses: %s\n        with:\n          go-version-file: '.go-version'\n", githubSetupGoAction)
}

// prepareHelperStepName and prepareHelperRun are the ONE definition of the helper
// preparation step, shared by the emitter and the validator so the rendered and accepted
// step orders cannot diverge.
const (
	prepareHelperStepName = "Prepare helper"
	prepareHelperRun      = "chmod +x ./nkd-exec"
)

func writePrepareHelperStep(out *bytes.Buffer) {
	fmt.Fprintf(out, "      - name: %s\n        run: %s\n", prepareHelperStepName, prepareHelperRun)
}

func writeDownloadStep(out *bytes.Buffer, name, path string) {
	fmt.Fprintf(out, "      - uses: %s\n        with:\n          name: %s\n          path: %s\n", githubDownloadAction, yamlSingle(name), yamlSingle(path))
}

func githubJobID(id string) string { return generatedJobID(id) }

func shortStableName(value string) string {
	clean := strings.ToLower(value)
	var out strings.Builder
	for _, r := range clean {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '-' {
			out.WriteRune(r)
		} else {
			out.WriteByte('-')
		}
	}
	result := strings.Trim(out.String(), "-")
	if len(result) <= 48 && result != "" {
		return result
	}
	sum := sha256.Sum256([]byte(value))
	if len(result) > 36 {
		result = result[:36]
	}
	return strings.Trim(result, "-") + "-" + hex.EncodeToString(sum[:6])
}

func githubArtifactName(id string) string { return "nkd-" + shortStableName(id) }

func carrierPath(id string) string {
	return filepath.ToSlash(filepath.Join(".nkd", "carriers", shortStableName(id)+".tar"))
}

func yamlSingle(value string) string { return "'" + strings.ReplaceAll(value, "'", "''") + "'" }

func shellQuote(value string) string {
	if value != "" && !strings.ContainsAny(value, " \t\r\n'\"\\$`;&|<>(){}[]*?!#~") {
		return value
	}
	return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
}

func regexpSecret(value string) bool {
	if value == "" {
		return false
	}
	for _, r := range value {
		if !((r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '_') {
			return false
		}
	}
	return true
}

func generatorLinkerFlags(value string) (string, error) {
	separator := strings.LastIndex(value, " (")
	if separator <= 0 || !strings.HasSuffix(value, ")") {
		return "", e.New(e.CodeInvalidCatalog, "factory generatorVersion %q must be 'version (commit)'", value)
	}
	version, commit := value[:separator], value[separator+2:len(value)-1]
	if !safeGeneratorToken(version) || !safeGeneratorToken(commit) {
		return "", e.New(e.CodeInvalidCatalog, "factory generatorVersion %q is unsafe", value)
	}
	return "-X main.version=" + version + " -X main.commit=" + commit, nil
}

func safeGeneratorToken(value string) bool {
	if value == "" {
		return false
	}
	for _, character := range value {
		if (character >= 'a' && character <= 'z') || (character >= 'A' && character <= 'Z') ||
			(character >= '0' && character <= '9') || strings.ContainsRune("._+/-", character) {
			continue
		}
		return false
	}
	return true
}

func sortedFileNames(files map[string][]byte) []string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// BundleIdentity binds the exact two-file execution bundle. PipelineBodyDigest omits
// only the generated provenance header (avoiding self-reference); NodesDigest hashes
// the exact canonical nodes.json bytes executed by nkd-exec.
type BundleIdentity struct {
	SchemaVersion       string `json:"schemaVersion"`
	Engine              string `json:"engine"`
	RecipeDigest        string `json:"recipeDigest"`
	PipelineBodyDigest  string `json:"pipelineBodyDigest"`
	NodesDigest         string `json:"nodesDigest"`
	TransportPlanDigest string `json:"transportPlanDigest"`
}

const BundleSchemaVersion = "nkd.dev/execution-bundle/v1"

// BundleDigest returns the domain-separated identity and its two exact file digests.
func BundleDigest(engine, recipeDigest string, nodes, pipelineBody []byte) (bundleDigest, nodesDigest, bodyDigest string, err error) {
	nodesDigest = FileDigest(nodes)
	bodyDigest = FileDigest(pipelineBody)
	var graph ir.Graph
	if err = canonical.UnmarshalExact(nodes, &graph); err != nil {
		return "", "", "", e.Wrap(e.CodePipelineDrift, err, "decoding canonical nodes.json for bundle identity")
	}
	graphDigest, digestErr := graph.Digest()
	if digestErr != nil {
		return "", "", "", e.Wrap(e.CodePipelineDrift, digestErr,
			"computing decoded nodes.json recipe identity")
	}
	if graphDigest != recipeDigest {
		return "", "", "", e.New(e.CodePipelineDrift,
			"execution bundle nodes identify recipe %s, caller supplied %s", graphDigest, recipeDigest)
	}
	transportPlan, planErr := TransportPlanJSON(&graph)
	if planErr != nil {
		return "", "", "", planErr
	}
	bundleDigest, err = canonical.Digest(canonical.KindBundle, BundleIdentity{
		SchemaVersion: BundleSchemaVersion, Engine: engine, RecipeDigest: recipeDigest,
		PipelineBodyDigest: bodyDigest, NodesDigest: nodesDigest, TransportPlanDigest: FileDigest(transportPlan),
	})
	return
}

// GeneratedPipelineBytes returns the standard provenance header followed by the
// exact body it identifies. It does not publish or qualify a provider workflow;
// adapter admission must succeed before this shared rendering seam is reached.
func GeneratedPipelineBytes(ctx context.Context, engine, recipeDigest, recipeID string, g *ir.Graph, body []byte) ([]byte, error) {
	if err := requireEmitterContext(ctx); err != nil {
		return nil, err
	}
	nodes, err := NodesJSON(g)
	if err != nil {
		return nil, err
	}
	if err := requireEmitterContext(ctx); err != nil {
		return nil, err
	}
	bd, nd, pd, err := BundleDigest(engine, recipeDigest, nodes, body)
	if err != nil {
		return nil, err
	}
	header := fmt.Sprintf(
		"# GENERATED BY nkdctl bundle — DO NOT EDIT (use the extension overlay or --emit-callable)\n"+
			"# bundleSchema: %s\n# recipe: %s\n# recipeDigest: %s\n"+
			"# pipelineBodyDigest: %s\n# nodesDigest: %s\n# transportPlanDigest: %s\n# bundleDigest: %s\n",
		BundleSchemaVersion, recipeID, recipeDigest, pd, nd, generatedTransportPlanDigest(g), bd)
	if err := requireEmitterContext(ctx); err != nil {
		return nil, err
	}
	result := make([]byte, 0, len(header)+len(body))
	result = append(result, header...)
	result = append(result, body...)
	return result, nil
}

func generatedTransportPlanDigest(g *ir.Graph) string {
	plan, err := TransportPlanJSON(g)
	if err != nil {
		return "invalid"
	}
	return FileDigest(plan)
}

// FileDigest is the exact byte digest used for execution-bundle members.
func FileDigest(b []byte) string {
	sum := sha256.Sum256(b)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// VerificationConfig names the fully-offline terminal-verifier inputs an admitted
// adapter must transport. The values convey no authority by themselves: every path is
// a committed relative input or explicitly transported workspace member, and the
// emitted verifier authenticates the exact bytes under the supplied role policy.
type VerificationConfig struct {
	Cosign            string
	CosignDigest      string
	ExpectedDigests   string
	Signature         string
	Certificate       string
	Bundle            string
	TrustedRoot       string
	TrustedRootDigest string
	Identity          string
	Issuer            string
	TrustStore        string

	Profile                  string
	ProfileSignature         string
	ProfileCertificate       string
	ProfileBundle            string
	ProfileTrustedRoot       string
	ProfileTrustedRootDigest string
	ProfileIdentity          string
	ProfileIssuer            string
}

// ValidateStatic rejects missing, unpinned, or unsafe terminal-verifier inputs
// without needing to inspect a graph. CLI adapters call it before catalog/profile
// I/O; Render repeats it through validate.
func (c VerificationConfig) ValidateStatic() error {
	type namedPath struct{ label, value string }
	requiredPaths := []namedPath{
		{"cosign", c.Cosign},
		{"expected-digests", c.ExpectedDigests},
		{"certificate", c.Certificate},
		{"bundle", c.Bundle},
		{"trusted-root", c.TrustedRoot},
	}
	if err := validateSHA256(c.CosignDigest); err != nil {
		return e.New(e.CodeUnpinnedInput,
			"emitted verify requires an exact --cosign-digest for its committed verifier executable: %v", err)
	}
	if err := validateSHA256(c.TrustedRootDigest); err != nil {
		return e.New(e.CodeUnpinnedInput,
			"emitted verify requires an exact --trusted-root-digest for its committed trusted root: %v", err)
	}
	if c.Signature != "" {
		requiredPaths = append(requiredPaths, namedPath{"signature", c.Signature})
	}
	if c.TrustStore != "" {
		requiredPaths = append(requiredPaths, namedPath{"trust-store", c.TrustStore})
	}
	if c.Issuer == "" || (c.Identity == "" && c.TrustStore == "") {
		return e.New(e.CodeTrustPolicyMissing, "emitted verify requires a pinned vector issuer and identity or explicit trust store")
	}
	for _, path := range requiredPaths {
		if err := validatePipelineInputPath(path.label, path.value); err != nil {
			return err
		}
	}
	return nil
}

// ValidateEmitterDataPath admits the optional catalog carrier before graph or
// filesystem work. Emitted jobs can reference only committed workspace-relative
// catalog paths.
func ValidateEmitterDataPath(value string) error {
	if strings.TrimSpace(value) == "" {
		return nil
	}
	return validatePipelineInputPath("data", value)
}

func (c VerificationConfig) validate(g *ir.Graph) error {
	if err := c.ValidateStatic(); err != nil {
		return err
	}
	if !graphHasBuild(g) {
		return nil
	}
	type namedPath struct{ label, value string }
	profilePaths := []namedPath{
		{"profile", c.Profile},
		{"profile-certificate", c.ProfileCertificate},
		{"profile-bundle", c.ProfileBundle},
		{"profile-trusted-root", c.ProfileTrustedRoot},
	}
	if c.ProfileSignature != "" {
		profilePaths = append(profilePaths, namedPath{"profile-signature", c.ProfileSignature})
	}
	if c.ProfileIssuer == "" || (c.ProfileIdentity == "" && c.TrustStore == "") {
		return e.New(e.CodeTrustPolicyMissing, "from-source emitted verify requires a pinned profile issuer and identity or explicit trust store")
	}
	if err := validateSHA256(c.ProfileTrustedRootDigest); err != nil {
		return e.New(e.CodeUnpinnedInput,
			"from-source emitted verify requires an exact --profile-trusted-root-digest: %v", err)
	}
	for _, path := range profilePaths {
		if err := validatePipelineInputPath(path.label, path.value); err != nil {
			return err
		}
	}
	return nil
}

func validatePipelineInputPath(label, value string) error {
	if strings.TrimSpace(value) == "" {
		return e.New(e.CodeTrustPolicyMissing, "emitted verify requires --%s", label)
	}
	clean := filepath.Clean(value)
	if filepath.IsAbs(value) || clean == "." || clean == ".." || strings.HasPrefix(clean, ".."+string(filepath.Separator)) {
		return e.New(e.CodeInvalidCatalog, "pipeline input --%s=%q must be a safe workspace-relative path", label, value)
	}
	return nil
}

func graphHasBuild(g *ir.Graph) bool {
	for _, n := range g.Nodes {
		if n.Kind == ir.KindBuild {
			return true
		}
	}
	return false
}

// verifyArgs renders the terminal verify invocation's argv (after `nkdctl`). It carries
// the FULL resolved criteria — a criteria drop would make the verify job re-resolve to a
// different recipe (or none: role/os are specific in real recipes, so `MatchField`
// fails and Resolve returns CodeNoMatch), and the unconditional fail-closed gate could
// then never go green — plus the operator's --data catalog path when a non-embedded
// catalog was used, so verify resolves the SAME recipe/recipeDigest the pipeline was
// emitted for. Wildcard/empty axes are omitted (they carry no constraint).
func verifyArgs(g *ir.Graph, data string, cfg VerificationConfig) ([]string, error) {
	if err := cfg.validate(g); err != nil {
		return nil, err
	}
	args := []string{"verify"}
	add := func(flag, v string) {
		if !criteria.IsWildcard(v) {
			args = append(args, flag, v)
		}
	}
	add("--role", g.Criteria.Role)
	add("--k8s", g.Criteria.K8sVersion)
	add("--os", g.Criteria.OS)
	add("--arch", g.Criteria.Arch)
	if data != "" {
		if err := ValidateEmitterDataPath(data); err != nil {
			return nil, err
		}
		args = append(args, "--data", data)
	}
	args = append(args,
		"--cosign", cfg.Cosign,
		"--cosign-digest", cfg.CosignDigest,
		"--expected-digests", cfg.ExpectedDigests,
		"--certificate", cfg.Certificate,
		"--bundle", cfg.Bundle,
		"--trusted-root", cfg.TrustedRoot,
		"--trusted-root-digest", cfg.TrustedRootDigest,
		"--issuer", cfg.Issuer,
		"--offline",
		"--results-dir", ResultDirectory(filepath.Join(".nkd", "work", "src")),
	)
	if cfg.Signature != "" {
		args = append(args, "--signature", cfg.Signature)
	}
	if cfg.Identity != "" {
		args = append(args, "--identity", cfg.Identity)
	}
	if cfg.TrustStore != "" {
		args = append(args, "--trust-store", cfg.TrustStore)
	}
	if graphHasBuild(g) {
		args = append(args,
			"--profile", cfg.Profile,
			"--profile-certificate", cfg.ProfileCertificate,
			"--profile-bundle", cfg.ProfileBundle,
			"--profile-trusted-root", cfg.ProfileTrustedRoot,
			"--profile-trusted-root-digest", cfg.ProfileTrustedRootDigest,
			"--profile-issuer", cfg.ProfileIssuer,
		)
		if cfg.ProfileSignature != "" {
			args = append(args, "--profile-signature", cfg.ProfileSignature)
		}
		if cfg.ProfileIdentity != "" {
			args = append(args, "--profile-identity", cfg.ProfileIdentity)
		}
	}
	return args, nil
}

// verifyCommand is verifyArgs joined into a `nkd-exec verify …` shell line.
func verifyCommand(g *ir.Graph, data string, cfg VerificationConfig) (string, error) {
	return verifyCommandWith(g, data, cfg, bootstrapHelper())
}

// verifyCommandWith is verifyCommand parameterized by helper delivery (ADR-18 §8).
func verifyCommandWith(g *ir.Graph, data string, cfg VerificationConfig, helper HelperRef) (string, error) {
	args, err := verifyArgs(g, data, cfg)
	if err != nil {
		return "", err
	}
	return shellJoin(append([]string{helper.Path}, args...)), nil
}

func shellJoin(args []string) string {
	quoted := make([]string, len(args))
	for i, arg := range args {
		quoted[i] = shellQuote(arg)
	}
	return strings.Join(quoted, " ")
}

func shellQuote(value string) string {
	if value != "" && !strings.ContainsAny(value, " \t\r\n'\"\\$`;&|<>(){}[]*?!#~") {
		return value
	}
	return "'" + strings.ReplaceAll(value, "'", `'"'"'`) + "'"
}

func validateEmitterContract(g *ir.Graph, runnerDigest string, verify VerificationConfig) error {
	if g == nil {
		return e.New(e.CodeInvalidCatalog, "pipeline emission requires an IR graph")
	}
	if err := g.Validate(); err != nil {
		return err
	}
	if graphHasBuild(g) {
		return e.New(e.CodeEngineCapability,
			"from-source emission requires a provider execution-attestation adapter that measures the actual runner, engine-selected container manifest, toolchain, sandbox, and closure before artifact work; no such adapter is configured")
	}
	if err := validateSHA256(runnerDigest); err != nil {
		return e.New(e.CodePreflightFailed, "emitted pipeline requires a canonical builder-profile runner digest: %v", err)
	}
	if err := verify.validate(g); err != nil {
		return err
	}
	jobs, err := LowerJobs(g)
	if err != nil {
		return err
	}
	for _, job := range jobs {
		if !strings.Contains(job.Image, "@sha256:") {
			return e.New(e.CodeEngineCapability, "job %q has no digest-pinned native container", job.Name)
		}
		parts := strings.Split(job.Image, "@")
		if len(parts) != 2 || parts[0] == "" || validateSHA256(parts[1]) != nil {
			return e.New(e.CodeEngineCapability, "job %q container %q is not a canonical digest reference", job.Name, job.Image)
		}
		if job.Kind == "build" && job.Network != ir.NetworkNone {
			return e.New(e.CodeEngineCapability, "build job %q does not request enforceable network denial", job.Name)
		}
	}
	return nil
}

// Provider renderers share ADR-18's one-IR adapter seam: LowerJobs owns executable
// topology, while admitted adapters map only provider syntax and authenticated
// transport. Shared lowering is not proof that every renderer is qualified. Current
// admission enables only the prebuilt GitLab lane; from-source provider emission and
// GitHub, Tekton, and Argo transport return CodeEngineCapability before output.

const (
	// NodesFile is the committed IR data file every job reads (ADR-18 §2). It is the
	// canonical graph; the runner selects one node from it by id.
	NodesFile = "nodes.json"
	// RunnerBinary is the from-source nkd-exec produced by the bootstrap job.
	RunnerBinary = "nkd-exec"
	// BootstrapJob builds + verifies that runner (ADR-18 §4) before any node runs.
	BootstrapJob = "build-runner"
)

// Extensions describes ADR-21 hook points for adapters that explicitly implement
// them. It grants no capability by itself. A provider route must reject extensions
// before output unless it renders every hook into the drift-identified bundle.
type Extensions struct {
	PreBuild   []string `json:"preBuild,omitempty" yaml:"preBuild,omitempty"`
	PostVerify []string `json:"postVerify,omitempty" yaml:"postVerify,omitempty"`
	PrePublish []string `json:"prePublish,omitempty" yaml:"prePublish,omitempty"`
}

// Job is the engine-agnostic lowered unit (ADR-18): a set of IR nodes interpreted by
// the pinned runner inside an engine-provided container. LowerJobs is the single
// IR-to-job mapping; a provider is usable only after its adapter proves it can preserve
// every declared dependency, input, output, receipt, and isolation requirement.
type Job struct {
	Name     string   // build-runner | fetch-* | build/pull-<component> | verify
	Image    string   // pinned container the engine runs the job in ("" = default base)
	Needs    []string // upstream job names
	Nodes    []string // IR node ids to exec
	Kind     string   // "bootstrap" | "fetch" | "build" | "pull" | "verify"
	Network  string   // ir.NetworkDefault | ir.NetworkNone
	Consumes []string // named engine artifacts downloaded before execution
	// Inputs carries the exact path allow-list for each consumed artifact. Names are
	// topology only; an adapter that transports bytes between isolated jobs must use
	// these bindings to unpack only the producer-declared roots.
	Inputs      []JobArtifact
	Produces    *JobArtifact
	NodesDigest string // exact digest of the nodes.json this job is authorized to execute
}

// JobArtifact is explicit cross-job transport. Paths are workspace-relative and
// names are stable; adapters must map every binding or reject emission.
type JobArtifact struct {
	Name  string
	Paths []string
}

// LowerJobs maps the IR to explicit network phases. Fetch/pull jobs may use the
// network; every compile is a separate NetworkNone job consuming a transported,
// receipted source closure. Combining fetch+build in one network-enabled job is
// forbidden because a declared offline node would not be enforced by the engine.
func LowerJobs(g *ir.Graph) ([]Job, error) {
	if g == nil {
		return nil, e.New(e.CodeInvalidCatalog, "pipeline lowering requires an IR graph")
	}
	if err := g.Validate(); err != nil {
		return nil, err
	}
	nodes := sortedNodes(g)
	for _, node := range nodes {
		if node.BuilderType == ir.BuilderBuildKit {
			return nil, e.New(e.CodeEngineCapability, "rootless BuildKit requires generated lifecycle Runs; qualified pipeline emission is unsupported")
		}
	}
	nodesJSON, err := NodesJSON(g)
	if err != nil {
		return nil, err
	}
	nodesDigest := FileDigest(nodesJSON)
	runnerArtifact := JobArtifact{Name: RunnerBinary, Paths: []string{RunnerBinary}}
	jobs := []Job{{Name: BootstrapJob, Kind: "bootstrap", Image: bootstrapImage, Network: ir.NetworkDefault, Produces: &runnerArtifact, NodesDigest: nodesDigest}}
	fetchArtifacts := map[string]string{}
	for _, n := range nodes {
		if n.Kind != ir.KindFetch {
			continue
		}
		artifactName := "source-" + sanitizeName(n.ID)
		fetchArtifacts[n.ID] = artifactName
		paths := []string{
			filepath.ToSlash(filepath.Join(".nkd", "work", "src", n.Dest)),
			filepath.ToSlash(filepath.Join(".nkd", "work", "source-receipts")),
		}
		image := n.VendorImage
		if image == "" {
			image = bootstrapImage
		}
		jobs = append(jobs, Job{
			Name: n.ID, Image: image, Needs: []string{BootstrapJob}, Nodes: []string{n.ID},
			Kind: "fetch", Network: ir.NetworkDefault, Consumes: []string{RunnerBinary}, Inputs: []JobArtifact{runnerArtifact},
			Produces: &JobArtifact{Name: artifactName, Paths: paths}, NodesDigest: nodesDigest,
		})
	}
	for _, n := range nodes {
		if n.Kind != ir.KindBuild {
			continue
		}
		src := fetchFor(nodes, n)
		resultName := "result-" + sanitizeName(n.ID)
		sourceArtifact := JobArtifact{Name: fetchArtifacts[src.ID], Paths: []string{
			filepath.ToSlash(filepath.Join(".nkd", "work", "src", src.Dest)),
			filepath.ToSlash(filepath.Join(".nkd", "work", "source-receipts")),
		}}
		jobs = append(jobs, Job{
			Name: "build-" + n.Component, Image: n.Toolchain, Needs: []string{BootstrapJob, src.ID},
			Nodes: []string{n.ID}, Kind: "build", Network: ir.NetworkNone,
			Consumes: []string{RunnerBinary, fetchArtifacts[src.ID]}, Inputs: []JobArtifact{runnerArtifact, sourceArtifact},
			Produces: &JobArtifact{Name: resultName, Paths: []string{
				filepath.ToSlash(filepath.Join(".nkd", "work", "out", sanitizeName(n.Component))),
				resultPath(n.ID),
			}}, NodesDigest: nodesDigest,
		})
	}
	for _, n := range nodes {
		if n.Kind != ir.KindPull {
			continue
		}
		jobs = append(jobs, Job{
			Name: "pull-" + n.Component, Image: bootstrapImage, Needs: []string{BootstrapJob},
			Nodes: []string{n.ID}, Kind: "pull", Network: ir.NetworkDefault,
			Consumes: []string{RunnerBinary}, Inputs: []JobArtifact{runnerArtifact},
			Produces: &JobArtifact{Name: "result-" + sanitizeName(n.ID), Paths: []string{
				filepath.ToSlash(filepath.Join(".nkd", "work", "fetch", sanitizeName(n.Component))),
				resultPath(n.ID),
			}}, NodesDigest: nodesDigest,
		})
	}
	verifyInputs := []string{RunnerBinary}
	verifyArtifacts := []JobArtifact{runnerArtifact}
	for _, j := range jobs {
		if j.Kind == "build" || j.Kind == "pull" {
			verifyInputs = append(verifyInputs, j.Produces.Name)
			verifyArtifacts = append(verifyArtifacts, *j.Produces)
		}
	}
	verifyNeeds := append([]string{BootstrapJob}, producerJobs(nodes)...)
	jobs = append(jobs, Job{Name: "verify", Kind: "verify", Image: bootstrapImage, Needs: verifyNeeds, Network: ir.NetworkNone, Consumes: verifyInputs, Inputs: verifyArtifacts, NodesDigest: nodesDigest})
	return jobs, nil
}

// EmittedRuntime is the container runtime the generated pipelines' build nodes orchestrate
// with under ADR-18 §8. Rootless podman is the default: `--network=none` needs no
// daemon, no privileged socket, and no bespoke runner (see ADR-18 §8).
const EmittedRuntime = "podman"

// HelperRef says how the pinned nkd-exec helper is delivered to a job (ADR-18 §8).
// The two variants sit BESIDE each other:
//   - bootstrap: the helper is built from pinned source and transported as an artifact,
//     so it is invoked as ./nkd-exec and re-hashed against the profile pin at every seam
//     (Guard). This is the self-hosting from-source helper (ADR-18 §4).
//   - image: the helper ships inside a digest-pinned job image on PATH, so it is invoked
//     as nkd-exec and the image digest — not a re-hash — pins the exact bytes (no Guard,
//     no from-source bootstrap job).
type HelperRef struct {
	Path  string // "./nkd-exec" (bootstrap) or "nkd-exec" (image, on PATH)
	Guard bool   // re-hash the transported binary against the profile pin (bootstrap only)
}

func bootstrapHelper() HelperRef { return HelperRef{Path: "./" + RunnerBinary, Guard: true} }
func imageHelper() HelperRef     { return HelperRef{Path: RunnerBinary, Guard: false} }

// NodeExec describes ONE Model-B node-execution invocation. It is the single per-node
// command BOTH emitter stacks render — the single-recipe pipeline emitter and the
// multi-recipe factory emitter — so the two share ONE isolation topology (ADR-18 §8)
// instead of hand-rolling divergent ones. Only NodeID/NodesDigest and the helper path are
// required; NodesFile defaults to the committed NodesFile and Runtime to EmittedRuntime, so
// the single-recipe lane renders byte-identically to the pre-unification form.
type NodeExec struct {
	NodeID      string // IR node id selected from the committed graph
	NodesFile   string // committed graph the helper reads (default NodesFile)
	NodesDigest string // exact sha256 of that graph; the helper rejects a mismatch
	SourceRoot  string // optional --source-root (the factory lane's per-recipe src root)
	Result      string // optional --result receipt path for cross-job verification
	Launch      bool   // ADR-18 §8: the helper orchestrates the pinned container itself
	Runtime     string // container runtime for --launch (default EmittedRuntime)
}

// ExecNodeCommand renders the uniform node-execution command (ADR-18 §2 / ADR-18 §8):
// the pinned helper executes one IR node read from the committed graph. NO build semantics
// are rendered here — they live in the graph. When Launch is set the helper ORCHESTRATES the
// pinned toolchain container itself (`<Runtime> run --network=none` for builds), so isolation
// is helper-enforced on a generic runner rather than delegated to an engine container block
// or a bespoke network-none runner tag.
func ExecNodeCommand(spec NodeExec, helper HelperRef) string {
	args := []string{helper.Path, "exec-node"}
	if spec.Launch {
		runtime := spec.Runtime
		if runtime == "" {
			runtime = EmittedRuntime
		}
		args = append(args, "--launch", "--runtime", runtime)
	}
	args = append(args, "--node", spec.NodeID, "--nodes-digest", spec.NodesDigest)
	if spec.SourceRoot != "" {
		args = append(args, "--source-root", spec.SourceRoot)
	}
	if spec.Result != "" {
		args = append(args, "--result", spec.Result)
	}
	nodesFile := spec.NodesFile
	if nodesFile == "" {
		nodesFile = NodesFile
	}
	return shellJoin(append(args, nodesFile))
}

// BootstrapHelperRef is the from-source helper delivery (./nkd-exec transported as an
// artifact). It is exported so the factory emitter can compose ExecNodeCommand with the same
// delivery convention the single-recipe lane uses, without re-deriving the "./"+RunnerBinary
// path. Image-mode delivery stays internal until a caller wires a digest-pinned helper image.
func BootstrapHelperRef() HelperRef { return bootstrapHelper() }

// runnerExec is the single-recipe lane's per-node command. It delegates to ExecNodeCommand
// with the committed NodesFile and the default runtime — no --source-root on this lane — so
// its output is byte-identical to the pre-unification form.
func runnerExec(nodeID, result, nodesDigest string, launch bool, helper HelperRef) string {
	return ExecNodeCommand(NodeExec{
		NodeID:      nodeID,
		NodesFile:   NodesFile,
		NodesDigest: nodesDigest,
		Result:      result,
		Launch:      launch,
		Runtime:     EmittedRuntime,
	}, helper)
}

// BootstrapScript builds the runner from pinned source and verifies it reproduces to
// the builder-profile's pinned runner digest — ADR-18 §4's self-hosting, from-source,
// VERIFIED runner. A missing pin is a hard error: an unverified executable cannot be
// the authority that interprets the signed execution graph. Static (CGO off) so it
// runs in any node's container.
func BootstrapScript(runnerDigest string) []string {
	if runnerDigest == "" {
		return []string{`echo "ERROR: builder profile has no runner digest; refusing an unverified CI runner" >&2`, "exit 1"}
	}
	return []string{
		"CGO_ENABLED=0 go build -trimpath -o " + RunnerBinary + " ./cmd/nkdctl",
		`GOT="sha256:$(sha256sum ` + RunnerBinary + ` | cut -d' ' -f1)"`,
		`test "$GOT" = "` + runnerDigest + `" || { echo "runner digest $GOT != profile pin ` + runnerDigest + `" >&2; exit 1; }`,
	}
}

// RunnerGuardScript re-hashes the runner at every execution seam. CI artifact
// transport is not an authority: only bytes reproducing to the signed profile pin
// may interpret nodes.json or authenticate terminal results.
func RunnerGuardScript(runnerDigest string) []string {
	return []string{
		`GOT="sha256:$(sha256sum ` + RunnerBinary + ` | cut -d' ' -f1)"`,
		`test "$GOT" = "` + runnerDigest + `" || { echo "transported runner digest $GOT != profile pin ` + runnerDigest + `" >&2; exit 1; }`,
		"chmod +x " + RunnerBinary,
	}
}

// guardScript re-hashes the transported helper in bootstrap mode; in image mode the helper
// is pinned by the job image digest, so there is nothing to re-hash.
func guardScript(helper HelperRef, runnerDigest string) []string {
	if !helper.Guard {
		return nil
	}
	return RunnerGuardScript(runnerDigest)
}

// ExecScript is the per-job body: authenticate the runner, then exec each node. Build
// nodes run in --launch mode (ADR-18 §8): the runner isolates them in a
// --network=none container itself, so the job needs no engine-provided network-none
// container and no bespoke runner tag.
func ExecScript(job Job, runnerDigest string) []string {
	return ExecScriptWith(job, runnerDigest, bootstrapHelper())
}

// ExecScriptWith is ExecScript parameterized by the helper delivery (ADR-18 §8).
func ExecScriptWith(job Job, runnerDigest string, helper HelperRef) []string {
	lines := guardScript(helper, runnerDigest)
	for _, id := range job.Nodes {
		result := ""
		if job.Kind == "build" || job.Kind == "pull" {
			result = resultPath(id)
			lines = append(lines, "mkdir -p "+filepath.ToSlash(filepath.Dir(result)))
		}
		lines = append(lines, runnerExec(id, result, job.NodesDigest, job.Kind == "build", helper))
	}
	return lines
}

// TransportArchivePath is the canonical, non-identity carrier pathname used by
// isolated-job adapters. Artifact names are generated by LowerJobs and sanitized;
// consumers still authenticate every unpacked identity-bearing member separately.
func TransportArchivePath(name string) string {
	return filepath.ToSlash(filepath.Join(".nkd", "transport", sanitizeName(name)+".tar"))
}

// PrepareTransportScript authenticates the runner before using it as the archive
// parser, then extracts each consumed producer archive through its exact allow-list.
func PrepareTransportScript(job Job, runnerDigest string) []string {
	return PrepareTransportScriptWith(job, runnerDigest, bootstrapHelper())
}

// PrepareTransportScriptWith is PrepareTransportScript parameterized by helper delivery.
func PrepareTransportScriptWith(job Job, runnerDigest string, helper HelperRef) []string {
	lines := guardScript(helper, runnerDigest)
	for _, input := range job.Inputs {
		if input.Name == RunnerBinary {
			continue // bootstrap mode transports this single file; image mode ships it on PATH.
		}
		args := []string{helper.Path, "transport-unpack", "--archive", TransportArchivePath(input.Name), "--root", "."}
		for _, member := range input.Paths {
			args = append(args, "--path", member)
		}
		lines = append(lines, shellJoin(args))
	}
	return lines
}

// ExecTransportScript is the isolated-job execution body used by artifact-based
// engines: validate inputs, execute the authorized nodes, then pack only the exact
// producer roots declared by LowerJobs.
func ExecTransportScript(job Job, runnerDigest string) []string {
	return ExecTransportScriptWith(job, runnerDigest, bootstrapHelper())
}

// ExecTransportScriptWith is ExecTransportScript parameterized by helper delivery.
func ExecTransportScriptWith(job Job, runnerDigest string, helper HelperRef) []string {
	lines := PrepareTransportScriptWith(job, runnerDigest, helper)
	for _, id := range job.Nodes {
		result := ""
		if job.Kind == "build" || job.Kind == "pull" {
			result = resultPath(id)
			lines = append(lines, "mkdir -p "+filepath.ToSlash(filepath.Dir(result)))
		}
		lines = append(lines, runnerExec(id, result, job.NodesDigest, job.Kind == "build", helper))
	}
	if job.Produces != nil && job.Produces.Name != RunnerBinary {
		archive := TransportArchivePath(job.Produces.Name)
		args := []string{helper.Path, "transport-pack", "--archive", archive, "--root", "."}
		for _, member := range job.Produces.Paths {
			args = append(args, "--path", member)
		}
		lines = append(lines, shellJoin(args))
	}
	return lines
}

func resultPath(nodeID string) string {
	return filepath.ToSlash(filepath.Join(".nkd", "work", "results", sanitizeName(nodeID)+".json"))
}

// NodesJSON is the committed IR data file the runner reads — the canonical full graph
// (ADR-18 §2's "pinned data file"), written alongside the emitted pipeline.
func NodesJSON(g *ir.Graph) ([]byte, error) {
	return g.CanonicalJSON()
}

// sortedNodes returns the graph's nodes in a stable order for emission.
func sortedNodes(g *ir.Graph) []ir.Node {
	nodes := append([]ir.Node(nil), g.Nodes...)
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].ID < nodes[j].ID })
	return nodes
}

// fetchFor returns the fetch node a build node depends on (its pinned source).
func fetchFor(nodes []ir.Node, build ir.Node) ir.Node {
	for _, dep := range build.Needs {
		for _, n := range nodes {
			if n.ID == dep && n.Kind == ir.KindFetch {
				return n
			}
		}
	}
	return ir.Node{}
}

// buildComponents returns the sorted "build-<component>" job names for the graph.
func buildComponents(nodes []ir.Node) []string {
	var jobs []string
	for _, n := range nodes {
		if n.Kind == ir.KindBuild {
			jobs = append(jobs, "build-"+n.Component)
		}
	}
	sort.Strings(jobs)
	return jobs
}

// pullComponents returns the sorted "pull-<component>" job names for the no-compile
// lane (NKD-FR-BLD-050).
func pullComponents(nodes []ir.Node) []string {
	var jobs []string
	for _, n := range nodes {
		if n.Kind == ir.KindPull {
			jobs = append(jobs, "pull-"+n.Component)
		}
	}
	sort.Strings(jobs)
	return jobs
}

// producerJobs returns the sorted build + pull job names — every job that yields an
// artifact, i.e. everything the terminal verify job must wait on.
func producerJobs(nodes []ir.Node) []string {
	jobs := append(buildComponents(nodes), pullComponents(nodes)...)
	sort.Strings(jobs)
	return jobs
}

func TestGeneratedInspectionFile(t *testing.T) {
	for _, tt := range []struct {
		name  string
		size  int
		bound int64
		want  e.Code
	}{
		{"exact bound", 128, 128, ""},
		{"empty", 0, 128, e.CodeVerifyFailed},
		{"overflow", 129, 128, e.CodeEngineCapability},
		{"absent bound", 1, 0, e.CodeEngineCapability},
	} {
		t.Run(tt.name, func(t *testing.T) {
			raw := bytes.Repeat([]byte("x"), tt.size)
			file, err := createGeneratedInspectionFile(t.Context(), tt.bound, func(destination io.Writer) error { _, err := destination.Write(raw); return err })
			if tt.want != "" {
				assertDependencyCode(t, err, tt.want)
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			defer file.Close()
			if file.Size() != int64(tt.size) {
				t.Fatalf("size=%d", file.Size())
			}
			if err := file.AssertUnchangedContext(t.Context()); err != nil {
				t.Fatal(err)
			}
			var copied bytes.Buffer
			if _, err := file.WriteToContext(t.Context(), &copied); err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(copied.Bytes(), raw) {
				t.Fatal("private generated bytes differ")
			}
			workspace := file.workspace
			if err := file.Close(); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(workspace); !os.IsNotExist(err) {
				t.Fatalf("private workspace leaked: %v", err)
			}
			assertDependencyCode(t, file.AssertUnchangedContext(t.Context()), e.CodeEngineCapability)
		})
	}
}

func TestGeneratedInspectionFileRejectsSubstitution(t *testing.T) {
	for _, tt := range []struct {
		name   string
		mutate func(*testing.T, *generatedInspectionFile)
	}{
		{"changed bytes", func(t *testing.T, f *generatedInspectionFile) {
			t.Helper()
			if _, err := f.file.WriteAt([]byte("b"), 0); err != nil {
				t.Fatal(err)
			}
		}},
		{"permissions", func(t *testing.T, f *generatedInspectionFile) {
			t.Helper()
			if err := f.file.Chmod(0o600); err != nil {
				t.Fatal(err)
			}
		}},
		{"sibling inode", func(t *testing.T, f *generatedInspectionFile) {
			t.Helper()
			path := filepath.Join(f.workspace, "subject")
			if err := os.Rename(path, filepath.Join(f.workspace, "original")); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte("aaaa"), 0o400); err != nil {
				t.Fatal(err)
			}
		}},
		{"symlink", func(t *testing.T, f *generatedInspectionFile) {
			t.Helper()
			path := filepath.Join(f.workspace, "subject")
			original := filepath.Join(f.workspace, "original")
			if err := os.Rename(path, original); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(original, path); err != nil {
				t.Fatal(err)
			}
		}},
	} {
		t.Run(tt.name, func(t *testing.T) {
			file, err := createGeneratedInspectionFile(t.Context(), 128, func(destination io.Writer) error { _, err := io.WriteString(destination, "aaaa"); return err })
			if err != nil {
				t.Fatal(err)
			}
			defer file.Close()
			tt.mutate(t, file)
			assertDependencyCode(t, file.AssertUnchangedContext(t.Context()), e.CodeVerifyFailed)
		})
	}
}

func TestGeneratedInspectionFileCancelled(t *testing.T) {
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	file, err := createGeneratedInspectionFile(ctx, 128, func(io.Writer) error { t.Fatal("canceled generation started"); return nil })
	if file != nil {
		t.Fatalf("canceled creation: %v", err)
	}
	assertDependencyCode(t, err, e.CodeTimeout)
}

func TestGeneratedInspectionPostCopyHashCancellation(t *testing.T) {
	for _, canceled := range []bool{false, true} {
		t.Run(map[bool]string{false: "uncanceled", true: "canceled after final write"}[canceled], func(t *testing.T) {
			file, err := os.CreateTemp(t.TempDir(), "completed-copy-")
			if err != nil {
				t.Fatal(err)
			}
			defer file.Close()
			ctx, cancel := context.WithCancel(t.Context())
			defer cancel()
			if _, err := io.WriteString(file, "complete transport bytes"); err != nil {
				t.Fatal(err)
			}
			if canceled {
				cancel()
			}
			digest, err := filesystemArchiveDigest(ctx, file)
			if canceled {
				assertDependencyCode(t, err, e.CodeTimeout)
				if digest != "" || !errors.Is(err, context.Canceled) || !strings.Contains(err.Error(), "hashing filesystem archive canceled") {
					t.Fatalf("wrong post-copy hash cancellation: digest=%q error=%v", digest, err)
				}
			} else if err != nil || digest != rawDigest([]byte("complete transport bytes")) {
				t.Fatalf("uncanceled complete copy changed: %q %v", digest, err)
			}
		})
	}
}

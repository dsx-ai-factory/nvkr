const QualificationManifestPath = ".github/nvkr-qualification/manifest.json"
const qualificationGeneratedHeader = "# GENERATED BY nvkr run generate --qualification-policy — DO NOT EDIT\n"
const qualificationGeneratedSchema = "nvkr.dev/generated-qualification/v1"
const maxQualificationWorkflowBytes = 128 << 10

// GeneratedWorkflows is a finite deterministic pair issued only by this renderer.
// It contains no authored policy, candidate files or qualification authority.
type GeneratedWorkflows struct {
	files    map[string][]byte
	manifest qualificationManifest
}

type qualificationManifest struct {
	SchemaVersion         string                    `json:"schemaVersion"`
	PlanDigest            string                    `json:"planDigest"`
	PolicyDigest          string                    `json:"policyDigest"`
	ProducerWorkflow      string                    `json:"producerWorkflow"`
	QualificationWorkflow string                    `json:"qualificationWorkflow"`
	SmokeWorkflow         string                    `json:"smokeWorkflow"`
	Members               []factory.GeneratedMember `json:"members"`
}

// Files returns defensive rendered bytes for review or external linting.
func (bundle *GeneratedWorkflows) Files() map[string][]byte {
	if bundle == nil {
		return nil
	}
	result := make(map[string][]byte, len(bundle.files))
	for name, raw := range bundle.files {
		result[name] = bytes.Clone(raw)
	}
	return result
}

// GenerateFiles composes the existing producer owner with a separately owned
// qualification pair. Both bundles are admitted before output. Each owner writes
// its manifest last; interruption across the owners is detected by --check and
// recovered by regeneration, not represented as one atomic repository commit.
func GenerateFiles(ctx context.Context, definitionPath, environmentPath, policyPath, generatorVersion, engine, root string, check bool) (string, error) {
	if err := generationContext(ctx); err != nil {
		return "", err
	}
	if err := factory.ValidateGenerationEngine(engine); err != nil {
		return "", err
	}
	if !qualificationInputPath(policyPath) {
		return "", e.New(e.CodeUsage, "qualification policy must have a clean repository-relative path")
	}
	policy, err := lifecycle.LoadQualificationPolicy(ctx, policyPath)
	if err != nil {
		return "", err
	}
	if err := admitQualificationGeneration(policy, policyPath); err != nil {
		return "", err
	}
	plan, err := lifecycle.CompileFiles(ctx, definitionPath, environmentPath, generatorVersion)
	if err != nil {
		return "", err
	}
	producer, err := factory.Render(ctx, plan, engine)
	if err != nil {
		return "", err
	}
	bundle, err := RenderWorkflows(ctx, plan, policy, policyPath)
	if err != nil {
		return "", err
	}
	if check {
		if err := factory.CheckGeneratedBundle(ctx, root, producer); err != nil {
			return "", err
		}
		if err := CheckWorkflows(ctx, root, bundle); err != nil {
			return "", err
		}
	} else {
		// Reject an ownership conflict before the producer owner publishes anything.
		if err := preflightQualificationWrite(ctx, root, bundle); err != nil {
			return "", err
		}
		if err := factory.WriteGeneratedBundle(ctx, root, producer); err != nil {
			return "", err
		}
		if err := WriteWorkflows(ctx, root, bundle); err != nil {
			return "", err
		}
	}
	return producer.PlanDigest, nil
}

func generationContext(ctx context.Context) error {
	if ctx == nil {
		return e.New(e.CodeUsage, "qualification generation requires context")
	}
	if err := ctx.Err(); err != nil {
		return e.Wrap(e.CodeTimeout, err, "qualification generation canceled")
	}
	return nil
}

var qualificationRelativePath = regexp.MustCompile(`^[A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*$`)

func qualificationInputPath(value string) bool {
	return qualificationRelativePath.MatchString(value) && path.Clean(value) == value && value != "." && value != ".." && !strings.HasPrefix(value, "../") && !strings.HasPrefix(value, ".github/nvkr-")
}
func admitQualificationGeneration(policy lifecycle.QualificationPolicy, policyPath string) error {
	if err := admitRunPolicy(policy); err != nil {
		return err
	}
	if !qualificationInputPath(policyPath) || policyPath == policy.Source.Workflow || policyPath == policy.QualificationWorkflow || (policy.Smoke != nil && policyPath == policy.Smoke.Workflow) {
		return e.New(e.CodeUsage, "qualification policy path overlaps generated files or is unsafe")
	}
	if policy.Source.Workflow != factory.GitHubWorkflowPath {
		return e.New(e.CodeEngineCapability, "qualification generation requires the selected generated producer workflow")
	}
	if policy.Cosign.Version == "" || policy.Cosign.PlatformDigests["linux/amd64"] == "" || policy.Cosign.Digest != "" || (policy.Cosign.Path != "" && policy.Cosign.Path != "cosign") {
		return e.New(e.CodeUnpinnedInput, "qualification generation requires an exact cosign version locator, the AMD64 final signer pin and every native worker pin, and the fixed cosign executable name")
	}
	return nil
}

// RenderWorkflows emits a workflow_run qualifier and its same-commit reusable
// native worker. Its action pins come from the trusted generation Plan's catalog;
// source workflow display name comes from that same producer renderer contract.
func RenderWorkflows(ctx context.Context, plan *factory.Plan, policy lifecycle.QualificationPolicy, policyPath string) (*GeneratedWorkflows, error) {
	if err := generationContext(ctx); err != nil {
		return nil, err
	}
	if err := admitQualificationGeneration(policy, policyPath); err != nil {
		return nil, err
	}
	if plan == nil {
		return nil, e.New(e.CodeUsage, "qualification generation requires a producer Plan")
	}
	if err := plan.Validate(); err != nil {
		return nil, err
	}
	if plan.Environment.Signing == nil || plan.Environment.Signing.Mode != factory.SigningModeCosign || plan.Environment.Signing.Issuer != "https://token.actions.githubusercontent.com" {
		return nil, e.New(e.CodeEngineCapability, "qualification generation requires a real GitHub-signing producer with exact-attempt handoff")
	}
	if err := admitQualificationRegistry(plan, policy); err != nil {
		return nil, err
	}
	if err := lifecycle.ValidateQualificationSmokePlan(plan, policy); err != nil {
		return nil, err
	}
	actions, err := pipeline.ResolveGitHubActions(plan.Actions)
	if err != nil {
		return nil, err
	}
	linker, err := factory.GeneratorLinkerFlags(plan.GeneratorVersion)
	if err != nil {
		return nil, err
	}
	planDigest, err := plan.Digest()
	if err != nil {
		return nil, err
	}
	policyDigest, err := policy.Digest()
	if err != nil {
		return nil, err
	}
	sourceAuth, err := qualificationSourceAuthentication(plan)
	if err != nil {
		return nil, err
	}
	var top, worker bytes.Buffer
	for _, out := range []*bytes.Buffer{&top, &worker} {
		fmt.Fprint(out, qualificationGeneratedHeader)
		fmt.Fprintf(out, "# policyDigest: %s\n", policyDigest)
	}
	fmt.Fprintf(&top, "name: %s\n'on':\n  workflow_run:\n    workflows: [%s]\n    types: [completed]\n    branches: [%s]\n", qualificationYAML("nvkr-qualify-"+plan.Name), qualificationYAML("nvkr-run-"+plan.Name), qualificationYAML(policy.Source.DefaultBranch))
	fmt.Fprint(&top, "permissions:\n  contents: read\nconcurrency:\n  group: nvkr-qualification-${{ github.workflow }}-${{ github.event.workflow_run.id }}-${{ github.event.workflow_run.run_attempt }}\n  cancel-in-progress: false\njobs:\n  native-smoke:\n    name: native-smoke\n")
	condition := "github.event_name == 'workflow_run' && github.event.workflow_run.conclusion == 'success' && github.repository == " + qualificationExpression(policy.Source.Repository) + " && github.event.workflow_run.head_branch == " + qualificationExpression(policy.Source.DefaultBranch) + " && github.event.workflow_run.repository.full_name == github.repository && github.event.workflow_run.head_repository.full_name == github.repository"
	fmt.Fprintf(&top, "    if: ${{ %s }}\n    uses: ./%s\n", condition, policy.Smoke.Workflow)
	qualificationPermissions(&top, "    ", false)
	sourceAuth.writeCallerSecrets(&top)
	// Run the existing authenticated owner after a failed worker so it can report
	// complete per-output refusal diagnostics. No failed worker becomes evidence.
	finalCondition := "!cancelled() && (needs.native-smoke.result == 'success' || needs.native-smoke.result == 'failure') && " + condition //nolint:misspell // GitHub status function uses this exact spelling.
	fmt.Fprintf(&top, "  qualify:\n    name: Qualify complete artifact set\n    needs: [native-smoke]\n    if: ${{ %s }}\n    runs-on: ubuntu-24.04\n    timeout-minutes: 30\n", finalCondition)
	qualificationPermissions(&top, "    ", true)
	fmt.Fprint(&top, "    steps:\n")
	qualificationBootstrap(&top, plan, actions, linker, policy, "amd64")
	fmt.Fprint(&top, "      - name: Authenticate all evidence and publish qualification\n        timeout-minutes: 20\n        env:\n          NVKR_GITHUB_TOKEN: ${{ github.token }}\n          NVKR_REGISTRY: ghcr.io\n          NVKR_REGISTRY_USER: ${{ github.actor }}\n          NVKR_REGISTRY_PASSWORD: ${{ github.token }}\n")
	sourceAuth.writeEnvironment(&top)
	fmt.Fprintf(&top, "        run: |\n          set -euo pipefail\n%s          ./nvkr-exec run qualify --policy %s\n", sourceAuth.requireTokens(), qualificationShell(policyPath))
	fmt.Fprintf(&worker, "name: %s\n'on':\n  workflow_call:\n", qualificationYAML("nvkr-smoke-"+plan.Name))
	sourceAuth.writeCallContract(&worker)
	fmt.Fprint(&worker, "permissions:\n  contents: read\nconcurrency:\n  group: nvkr-native-smoke-${{ github.run_id }}-${{ github.run_attempt }}\n  cancel-in-progress: false\njobs:\n  native:\n    name: native-${{ matrix.arch }}\n    runs-on: ${{ matrix.runner }}\n    timeout-minutes: 30\n    strategy:\n      fail-fast: false\n      matrix:\n        include:\n")
	platforms := make([]string, 0, len(policy.Smoke.Images))
	for platform := range policy.Smoke.Images {
		platforms = append(platforms, platform)
	}
	sort.Strings(platforms)
	for _, platform := range platforms {
		arch := strings.TrimPrefix(platform, "linux/")
		runner := "ubuntu-24.04"
		if arch == "arm64" {
			runner += "-arm"
		}
		fmt.Fprintf(&worker, "          - arch: %s\n            runner: %s\n            image: %s\n            cosign-digest: %s\n", arch, runner, qualificationYAML(policy.Smoke.Images["linux/"+arch]), qualificationYAML(policy.Cosign.PlatformDigests["linux/"+arch]))
	}
	qualificationPermissions(&worker, "    ", false)
	fmt.Fprint(&worker, "    steps:\n")
	qualificationBootstrap(&worker, plan, actions, linker, policy, "")
	worker.WriteString("      - name: Acquire pinned native smoke image\n        timeout-minutes: 5\n        env:\n          SMOKE_IMAGE: ${{ matrix.image }}\n          SMOKE_ARCH: ${{ matrix.arch }}\n          GHCR_USER: ${{ github.actor }}\n          GHCR_TOKEN: ${{ github.token }}\n        run: |\n          set -euo pipefail\n          export DOCKER_CONFIG=\"$RUNNER_TEMP/nvkr-smoke-pull\"\n          mkdir -m 0700 \"$DOCKER_CONFIG\"\n          printf '%s' \"$GHCR_TOKEN\" | docker login ghcr.io --username \"$GHCR_USER\" --password-stdin\n          docker pull --platform \"linux/$SMOKE_ARCH\" \"$SMOKE_IMAGE\"\n")
	fmt.Fprint(&worker, "      - name: Authenticate and smoke exact delivered tool bytes\n        timeout-minutes: 20\n        env:\n          NVKR_GITHUB_TOKEN: ${{ github.token }}\n          NVKR_PULL_REGISTRY: ghcr.io\n          NVKR_PULL_REGISTRY_USER: ${{ github.actor }}\n          NVKR_PULL_REGISTRY_PASSWORD: ${{ github.token }}\n")
	sourceAuth.writeEnvironment(&worker)
	fmt.Fprintf(&worker, "        run: |\n          set -euo pipefail\n%s          ./nvkr-exec run smoke-worker --policy %s\n", sourceAuth.requireTokens(), qualificationShell(policyPath))
	fmt.Fprintf(&worker, "      - name: Upload signed native smoke evidence\n        uses: %s # %s\n        timeout-minutes: 5\n        with:\n          name: nvkr-smoke-${{ github.run_id }}-${{ github.run_attempt }}-${{ matrix.arch }}\n          path: |\n            .nvkr/smoke-worker/evidence/worker.json\n            .nvkr/smoke-worker/evidence/worker.sig\n            .nvkr/smoke-worker/evidence/worker.pem\n            .nvkr/smoke-worker/evidence/worker.bundle.json\n          include-hidden-files: true\n          if-no-files-found: error\n", actions.Upload, plan.Actions["upload-artifact"].Version)
	files := map[string][]byte{policy.QualificationWorkflow: top.Bytes(), policy.Smoke.Workflow: worker.Bytes()}
	members := make([]factory.GeneratedMember, 0, 2)
	for name, raw := range files {
		if len(raw) > maxQualificationWorkflowBytes {
			return nil, e.New(e.CodeEngineCapability, "qualification workflow exceeds its byte bound")
		}
		members = append(members, factory.GeneratedMember{Path: name, SHA256: pipeline.FileDigest(raw), Mode: 0o644})
	}
	sort.Slice(members, func(i, j int) bool { return members[i].Path < members[j].Path })
	return &GeneratedWorkflows{files: files, manifest: qualificationManifest{SchemaVersion: qualificationGeneratedSchema, PlanDigest: planDigest, PolicyDigest: policyDigest, ProducerWorkflow: policy.Source.Workflow, QualificationWorkflow: policy.QualificationWorkflow, SmokeWorkflow: policy.Smoke.Workflow, Members: members}}, nil
}

func qualificationPermissions(out *bytes.Buffer, indent string, signing bool) {
	packages := "read"
	if signing {
		packages = "write"
	}
	fmt.Fprintf(out, "%spermissions:\n%s  contents: read\n%s  actions: read\n%s  packages: %s\n%s  id-token: write\n", indent, indent, indent, indent, packages, indent)
}
func qualificationYAML(value string) string       { return "'" + strings.ReplaceAll(value, "'", "''") + "'" }
func qualificationExpression(value string) string { return qualificationYAML(value) }
func qualificationShell(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

func admitQualificationRegistry(plan *factory.Plan, policy lifecycle.QualificationPolicy) error {
	namespace := "ghcr.io/" + strings.ToLower(strings.Split(policy.Source.Repository, "/")[0]) + "/"
	publication := plan.Environment.Publication
	if publication == nil || !strings.HasPrefix(publication.RepositoryPrefix, namespace) || publication.Anonymous || publication.CredentialRef != "github:GITHUB_TOKEN" {
		return e.New(e.CodeEngineCapability, "qualification generation requires GHCR publication in the trusted source owner namespace using github:GITHUB_TOKEN")
	}
	for _, target := range plan.Targets {
		if !strings.HasPrefix(target.Ref, namespace) || target.PlainHTTP || target.Anonymous || target.CredentialRef != "github:GITHUB_TOKEN" {
			return e.New(e.CodeEngineCapability, "qualification generation requires every publication target in the admitted GHCR namespace")
		}
	}
	return nil
}

func qualificationBootstrap(out *bytes.Buffer, plan *factory.Plan, actions pipeline.GitHubActionRefs, linker string, policy lifecycle.QualificationPolicy, arch string) {
	out.WriteString("      - name: Admit trusted same-commit workflow\n        timeout-minutes: 1\n        run: |\n          set -euo pipefail\n          test -n \"$GITHUB_SHA\"\n          test \"$GITHUB_WORKFLOW_SHA\" = \"$GITHUB_SHA\"\n")
	fmt.Fprintf(out, "      - name: Check out trusted qualifier commit\n        uses: %s # %s\n        with:\n          ref: ${{ github.workflow_sha }}\n          persist-credentials: false\n      - name: Set up pinned Go\n        uses: %s # %s\n        with:\n          go-version-file: .go-version\n          cache: false\n      - name: Build trusted qualifier\n        timeout-minutes: 5\n        env:\n          GOTOOLCHAIN: local\n          CGO_ENABLED: '0'\n        run: go build -trimpath -ldflags %s -o nvkr-exec ./cmd/nvkr\n", actions.Checkout, plan.Actions["checkout"].Version, actions.SetupGo, plan.Actions["setup-go"].Version, qualificationShell(linker))
	digest := policy.Cosign.PlatformDigests["linux/"+arch]
	if arch == "" {
		arch = "${{ matrix.arch }}"
		digest = "${{ matrix.cosign-digest }}"
	}
	fmt.Fprintf(out, "      - name: Install independently pinned cosign\n        timeout-minutes: 5\n        env:\n          COSIGN_VERSION: %s\n          COSIGN_ARCH: %s\n          COSIGN_DIGEST: %s\n        run: |\n          set -euo pipefail\n          tools=\"$RUNNER_TEMP/nvkr-qualifier-tools\"\n          mkdir -m 0700 \"$tools\"\n          curl --proto '=https' --tlsv1.2 --fail --location --connect-timeout 10 --max-time 120 --retry 2 --output \"$tools/cosign\" \"https://github.com/sigstore/cosign/releases/download/$COSIGN_VERSION/cosign-linux-$COSIGN_ARCH\"\n          printf '%%s  %%s\\n' \"${COSIGN_DIGEST#sha256:}\" \"$tools/cosign\" | sha256sum --check --strict -\n          chmod 0500 \"$tools/cosign\"\n          printf '%%s\\n' \"$tools\" >> \"$GITHUB_PATH\"\n", qualificationYAML(policy.Cosign.Version), qualificationYAML(arch), qualificationYAML(digest))
}

func (bundle *GeneratedWorkflows) manifestBytes() ([]byte, error) {
	if bundle == nil {
		return nil, e.New(e.CodeUsage, "qualification workflow bundle is required")
	}
	if err := bundle.manifest.validate(); err != nil {
		return nil, err
	}
	if len(bundle.files) != 2 {
		return nil, e.New(e.CodePipelineDrift, "qualification workflow bundle has an incomplete file set")
	}
	for _, member := range bundle.manifest.Members {
		raw, ok := bundle.files[member.Path]
		if !ok || len(raw) > maxQualificationWorkflowBytes || !bytes.HasPrefix(raw, []byte(qualificationGeneratedHeader)) || pipeline.FileDigest(raw) != member.SHA256 {
			return nil, e.New(e.CodePipelineDrift, "qualification workflow bytes differ from their manifest")
		}
	}
	raw, err := canonical.Marshal(bundle.manifest)
	if err != nil {
		return nil, e.Wrap(e.CodeInternal, err, "encoding qualification ownership manifest")
	}
	return append(raw, '\n'), nil
}

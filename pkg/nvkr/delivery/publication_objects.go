// PublicationObject describes one exact member of a captured OCI layout. Key is
// relative to that layout, not a destination or authorization. Blob media types
// remain in the original checked OCI descriptors; opaque blob transfers use
// application/octet-stream without changing those declarations.
type PublicationObject struct {
	Key       string
	SHA256    string
	Size      int64
	MediaType string
	// DiskOutputs binds a held raw disk to each exact named output. It is
	// derived from checked publication membership, never from a filename.
	DiskOutputs []string
}

type publicationObjectSource struct {
	description PublicationObject
	source      io.ReaderAt
	check       func() error
}

// VisitObjects lends the complete captured layout in unique key order, including
// index.json, every payload/control/evidence blob, and the standard oci-layout
// marker generated by WriteLayout. It never reopens a source pathname or grants
// signature, policy, release or storage authority. Detached registry signatures
// not contained in this checked closure must be retained by their owning module.
//
// A reader is valid only during its synchronous callback. Complete sequential
// reads check the original digest and size; Seek supports replay of those same
// bytes. A callback may skip reading after independently verifying equal remote
// bytes. Returning nil is not proof that the callback uploaded or authenticated
// anything. Previously delivered objects cannot be rolled back on later failure.
//
// Callbacks run under the shared publication lifetime lock and must bound their
// own I/O, honor ctx, and join any workers before returning. They must not reenter
// or Close this publication, or wait for work that does so. Concurrent Close
// waits for visitation, and does not cancel or preempt a callback.
func (publication *Publication) VisitObjects(ctx context.Context,
	visit func(context.Context, PublicationObject, io.ReadSeeker) error,
) error {
	if err := deliveryContext(ctx); err != nil {
		return err
	}
	if publication == nil || publication.publicationState == nil {
		return e.New(e.CodeGateUnmet, "object visitation requires an open publication")
	}
	if visit == nil {
		return e.New(e.CodeUsage, "publication object visitor is required")
	}
	publication.mu.RLock()
	defer publication.mu.RUnlock()
	if publication.closed || len(publication.files) == 0 || publication.inspection.Root.Release == nil {
		return e.New(e.CodeGateUnmet, "publication is not open")
	}
	sources, err := publication.objectSources(ctx)
	if err != nil {
		return err
	}
	for _, source := range sources {
		if err := deliveryContext(ctx); err != nil {
			return err
		}
		if err := source.check(); err != nil {
			return err
		}
		if err := visitPublicationObject(ctx, source, visit); err != nil {
			var coded *e.Error
			if !errors.As(err, &coded) {
				err = e.Wrap(e.CodeVerifyFailed, err, "visiting publication object %q", source.description.Key)
			}
			return classifyContext(ctx, err)
		}
	}
	return nil
}

// Revoke even if a callback panics and its caller recovers outside visitation.
func visitPublicationObject(ctx context.Context, source publicationObjectSource,
	visit func(context.Context, PublicationObject, io.ReadSeeker) error,
) (returnErr error) {
	reader := newPublicationObjectReader(ctx, source)
	defer func() { returnErr = errors.Join(reader.revoke(), returnErr, deliveryContext(ctx)) }()
	return visit(ctx, source.description, reader)
}

// The caller holds the publication lifetime lock. Sources are capabilities, not
// reconstructed locators; metadata from a detached description is never accepted.
func (publication *Publication) objectSources(ctx context.Context) ([]publicationObjectSource, error) {
	if publication.files[0] == nil || publication.files[0].Digest() != publication.inspection.RootDigest {
		return nil, e.New(e.CodeVerifyFailed, "held publication index differs from its checked root")
	}
	sources := make([]publicationObjectSource, 0, len(publication.files)+len(publication.diskPayloads)+1)
	for i, file := range publication.files {
		if file == nil || !isDigest(file.Digest()) {
			return nil, e.New(e.CodeVerifyFailed, "publication contains an invalid held object")
		}
		key, media := "blobs/sha256/"+strings.TrimPrefix(file.Digest(), "sha256:"), "application/octet-stream"
		if i == 0 {
			key, media = "index.json", MediaOCIIndex
		}
		expected := file.Size()
		sources = append(sources, publicationObjectSource{
			description: PublicationObject{Key: key, SHA256: file.Digest(), Size: expected, MediaType: media},
			source:      file,
			check:       func() error { return checkPublicationObjectSize(ctx, file.OSFile(), expected) },
		})
	}
	diskSizes := make(map[string]int64, len(publication.diskPayloads))
	diskOutputs := make(map[string][]string, len(publication.diskPayloads))
	for _, output := range publication.outputs {
		if output.Disk == nil {
			continue
		}
		digest, size := output.Disk.PayloadDigest, output.Disk.Size
		if previous, ok := diskSizes[digest]; ok && previous != size {
			return nil, e.New(e.CodeVerifyFailed, "shared disk payload has conflicting sizes")
		}
		if publication.diskPayloads[digest] == nil {
			return nil, e.New(e.CodeVerifyFailed, "disk output has no held payload")
		}
		diskSizes[digest] = size
		diskOutputs[digest] = append(diskOutputs[digest], output.Name)
	}
	for digest, file := range publication.diskPayloads {
		size, ok := diskSizes[digest]
		if !ok || !isDigest(digest) || size <= 0 {
			return nil, e.New(e.CodeVerifyFailed, "held disk lacks its checked output binding")
		}
		sort.Strings(diskOutputs[digest])
		sources = append(sources, publicationObjectSource{
			description: PublicationObject{Key: "blobs/sha256/" + strings.TrimPrefix(digest, "sha256:"), SHA256: digest, Size: size, MediaType: "application/octet-stream", DiskOutputs: diskOutputs[digest]},
			source:      file,
			check:       func() error { return checkPublicationObjectSize(ctx, file, size) },
		})
	}
	marker := []byte(`{"imageLayoutVersion":"1.0.0"}`)
	sources = append(sources, publicationObjectSource{
		description: PublicationObject{Key: "oci-layout", SHA256: digestBytes(marker), Size: int64(len(marker)), MediaType: "application/json"},
		source:      bytes.NewReader(marker), check: func() error { return nil },
	})
	sort.Slice(sources, func(i, j int) bool { return sources[i].description.Key < sources[j].description.Key })
	for i, source := range sources {
		if i > 0 && source.description.Key == sources[i-1].description.Key {
			return nil, e.New(e.CodeVerifyFailed, "publication contains duplicate held object keys")
		}
	}
	return sources, nil
}

func checkPublicationObjectSize(ctx context.Context, file *os.File, expected int64) error {
	if err := deliveryContext(ctx); err != nil {
		return err
	}
	if file == nil {
		return e.New(e.CodeGateUnmet, "publication object is closed")
	}
	info, err := file.Stat()
	if err != nil {
		return e.Wrap(e.CodeVerifyFailed, err, "checking held publication object")
	}
	if err := deliveryContext(ctx); err != nil {
		return err
	}
	if !info.Mode().IsRegular() || info.Size() != expected {
		return e.New(e.CodeVerifyFailed, "held publication object size or mode changed")
	}
	return nil
}

// The standard SectionReader supplies bounded seeking over the existing held
// inode. This wrapper adds the callback lease, cancellation and full-pass digest
// check without exposing a file descriptor or allocating another disk snapshot.
type publicationObjectReader struct {
	mu         sync.Mutex
	ctx        context.Context
	source     publicationObjectSource
	section    *io.SectionReader
	active     bool
	hash       hash.Hash
	hashed     int64
	sequential bool
	failure    error
}

func newPublicationObjectReader(ctx context.Context, source publicationObjectSource) *publicationObjectReader {
	return &publicationObjectReader{ctx: ctx, source: source, section: io.NewSectionReader(source.source, 0, source.description.Size), active: true, hash: sha256.New(), sequential: true}
}

// objectStoreHeldBody marks the private, callback-scoped immutable source for
// synchronous object-store borrowing. It does not transfer ownership or bypass
// that adapter's independent hash/size checks and conditional-write admission.
func (*publicationObjectReader) objectStoreHeldBody() {}

func (reader *publicationObjectReader) Read(buffer []byte) (int, error) {
	reader.mu.Lock()
	defer reader.mu.Unlock()
	if err := reader.available(); err != nil {
		return 0, err
	}
	offset, err := reader.section.Seek(0, io.SeekCurrent)
	if err != nil {
		return 0, reader.fail(err)
	}
	n, readErr := reader.section.Read(buffer)
	if reader.sequential && offset == reader.hashed {
		_, _ = reader.hash.Write(buffer[:n])
		reader.hashed += int64(n)
		if reader.hashed == reader.source.description.Size {
			if err := reader.source.check(); err != nil {
				return n, reader.fail(err)
			}
			if "sha256:"+hex.EncodeToString(reader.hash.Sum(nil)) != reader.source.description.SHA256 {
				return n, reader.fail(e.New(e.CodeVerifyFailed, "publication object stream differs from its exact digest"))
			}
		}
	} else {
		reader.sequential = false
	}
	if readErr != nil && (!errors.Is(readErr, io.EOF) || offset+int64(n) < reader.source.description.Size) {
		return n, reader.fail(e.Wrap(e.CodeVerifyFailed, readErr, "reading complete held publication object"))
	}
	if err := deliveryContext(reader.ctx); err != nil {
		return n, reader.fail(err)
	}
	return n, readErr
}

func (reader *publicationObjectReader) Seek(offset int64, whence int) (int64, error) {
	reader.mu.Lock()
	defer reader.mu.Unlock()
	if err := reader.available(); err != nil {
		return 0, err
	}
	previous, err := reader.section.Seek(0, io.SeekCurrent)
	if err != nil {
		return 0, reader.fail(err)
	}
	next, err := reader.section.Seek(offset, whence)
	if err != nil {
		return 0, e.Wrap(e.CodeUsage, err, "seeking held publication object")
	}
	if next == 0 {
		reader.hash.Reset()
		reader.hashed = 0
		reader.sequential = true
	} else if next != previous {
		reader.sequential = false
	}
	return next, nil
}

func (reader *publicationObjectReader) available() error {
	if !reader.active {
		return e.New(e.CodeGateUnmet, "publication object reader is outside its callback")
	}
	if reader.failure != nil {
		return reader.failure
	}
	if err := deliveryContext(reader.ctx); err != nil {
		return reader.fail(err)
	}
	return nil
}

func (reader *publicationObjectReader) fail(err error) error {
	reader.failure = classifyContext(reader.ctx, err)
	return reader.failure
}

func (reader *publicationObjectReader) revoke() error {
	reader.mu.Lock()
	defer reader.mu.Unlock()
	reader.active = false
	reader.section = nil
	reader.source = publicationObjectSource{}
	reader.hash = nil
	reader.ctx = nil
	return reader.failure
}

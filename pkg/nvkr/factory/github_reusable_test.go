func TestGitHubReusableLoweringRejectsAmbiguousOrUnboundedTemplates(t *testing.T) {
	plan, actions, fixture := githubReusableFixture(t)
	for _, test := range []struct {
		name string
		edit func(*yamlv3.Node)
	}{
		{name: "zero timeout", edit: func(jobs *yamlv3.Node) {
			githubYAMLField(githubYAMLField(jobs, "first"), "timeout-minutes").Value = "0"
		}},
		{name: "excess timeout", edit: func(jobs *yamlv3.Node) {
			githubYAMLField(githubYAMLField(jobs, "first"), "timeout-minutes").Value = "361"
		}},
		{name: "string timeout", edit: func(jobs *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(jobs, "first"), "timeout-minutes", githubYAMLString("60"))
		}},
		{name: "same semantic name different bytes", edit: func(jobs *yamlv3.Node) {
			steps := githubYAMLField(githubYAMLField(jobs, "second"), "steps")
			githubYAMLField(steps.Content[0], "run").Value += "\n"
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			root, err := githubResolveAliases(fixture, map[*yamlv3.Node]bool{})
			if err != nil {
				t.Fatal(err)
			}
			test.edit(githubYAMLField(root, "jobs"))
			files := map[string][]byte{}
			_, err = lowerGitHubReusableWorkflows(plan, githubReusableBytes(t, root), files, actions)
			assertFactoryErrorCode(t, err, e.CodeEngineCapability)
			if len(files) != 0 {
				t.Fatal("failed lowering returned partial generated templates")
			}
		})
	}
}

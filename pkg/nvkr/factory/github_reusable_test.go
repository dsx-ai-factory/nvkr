func githubReusableFixture(t *testing.T) (*Plan, githubActionRefs, *yamlv3.Node) {
	t.Helper()
	plan := githubTestPlan(t)
	plan.Environment.GitHubRunners = map[string]string{"linux/amd64": "ubuntu-24.04", "linux/arm64": "ubuntu-24.04-arm"}
	actions := testActionRefs(t, plan)
	jobs := githubYAMLMap()
	for _, fixture := range []struct {
		id, runner string
		pair       bool
	}{
		{id: "first", runner: "ubuntu-24.04"},
		{id: "second", runner: "ubuntu-24.04"},
		{id: "observation", runner: "ubuntu-24.04", pair: true},
		{id: "arm", runner: "ubuntu-24.04-arm"},
		{id: "protected", runner: "ubuntu-24.04"},
	} {
		job := githubStepSequenceFixture(t, plan, actions, fixture.runner)
		githubYAMLSet(job, "name", githubYAMLString("Stage "+fixture.id))
		githubYAMLSet(job, "timeout-minutes", &yamlv3.Node{Kind: yamlv3.ScalarNode, Tag: "!!int", Value: "60"})
		githubYAMLSet(job, "needs", &yamlv3.Node{Kind: yamlv3.SequenceNode, Tag: "!!seq", Content: []*yamlv3.Node{githubYAMLString("bootstrap")}})
		githubYAMLSet(job, "if", githubYAMLString("${{ "+githubExecutionCondition+" }}"))
		if fixture.pair {
			githubYAMLSet(job, "if", githubYAMLString("${{ always() && "+githubExecutionCondition+" }}"))
			steps := githubYAMLField(job, "steps")
			steps.Content = append(steps.Content, githubYAMLMap("name", githubYAMLString("execute node part-2"),
				"uses", githubYAMLString("./"+githubActionsDirectoryFor(plan)+"shared/execute-node"),
				"with", githubYAMLMap("parameters", githubYAMLString(githubParametersExpression("part-2")))))
		}
		if fixture.id == "protected" {
			githubYAMLSet(job, "environment", githubYAMLString("nkd-release"))
			githubYAMLSet(job, "permissions", githubYAMLMap("id-token", githubYAMLString("write")))
		}
		githubYAMLSet(jobs, fixture.id, job)
	}
	root := githubYAMLMap("name", githubYAMLString("Reusable contract"), "on", githubYAMLMap("workflow_dispatch", githubYAMLMap()),
		"permissions", githubYAMLMap("contents", githubYAMLString("read")), "jobs", jobs)
	root.HeadComment = "GENERATED BY nvkr run generate — DO NOT EDIT"
	return plan, actions, root
}

func githubReusableBytes(t *testing.T, node *yamlv3.Node) []byte {
	t.Helper()
	raw, err := encodeGitHubYAML(node)
	if err != nil {
		t.Fatal(err)
	}
	return raw
}

func TestGitHubReusableWorkflowsPreserveExactJobs(t *testing.T) {
	plan, actions, root := githubReusableFixture(t)
	before := githubReusableBytes(t, root)
	if err := anchorGitHubPreflight(plan, githubYAMLField(root, "jobs"), actions); err != nil {
		t.Fatal(err)
	}
	raw := githubReusableBytes(t, root)
	files := map[string][]byte{}
	lowered, err := lowerGitHubReusableWorkflows(plan, raw, files, actions)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 3 {
		t.Fatalf("got %d templates, want three stable native sequence profiles", len(files))
	}
	if !bytes.Contains(lowered, []byte("# GENERATED BY nvkr run generate")) {
		t.Fatal("lowering lost the entry workflow header")
	}
	for _, token := range []string{"execute-ubuntu-24-04-node", "execute-ubuntu-24-04-two-nodes", "execute-ubuntu-24-04-arm-node"} {
		if len(files[githubReusableWorkflowPath(plan, token)]) == 0 {
			t.Fatalf("missing semantic template %s", token)
		}
	}
	for range 2 {
		expanded, err := expandGitHubReusableWorkflows(t.Context(), plan, lowered, files)
		if err != nil {
			t.Fatal(err)
		}
		want, err := yaml.YAMLToJSONStrict(before)
		if err != nil {
			t.Fatal(err)
		}
		got, err := yaml.YAMLToJSONStrict(expanded)
		if err != nil || !bytes.Equal(got, want) {
			t.Fatalf("reusable expansion changed exact jobs, policy, selectors, or steps: %v", err)
		}
	}
	_, jobs, err := githubReusableDocument(lowered)
	if err != nil {
		t.Fatal(err)
	}
	if githubYAMLField(githubYAMLField(jobs, "protected"), "uses") != nil {
		t.Fatal("protected signing job moved into a reusable workflow")
	}
	repeated, err := lowerGitHubReusableWorkflows(plan, raw, map[string][]byte{}, actions)
	if err != nil || !bytes.Equal(repeated, lowered) {
		t.Fatalf("same-input lowering is not deterministic: %v", err)
	}
}

func TestGitHubReusableWorkflowsRejectChangedInterfaces(t *testing.T) {
	plan, actions, root := githubReusableFixture(t)
	files := map[string][]byte{}
	raw, err := lowerGitHubReusableWorkflows(plan, githubReusableBytes(t, root), files, actions)
	if err != nil {
		t.Fatal(err)
	}
	childPath := githubReusableWorkflowPath(plan, "execute-ubuntu-24-04-node")
	for _, test := range []struct {
		name   string
		child  bool
		mutate func(*yamlv3.Node)
	}{
		{name: "sibling selector", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(job, "with"), "stage", githubYAMLString("second"))
		}},
		{name: "selector expression", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(job, "with"), "stage", githubYAMLString("${{ github.job }}"))
		}},
		{name: "timeout expression", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(job, "with"), "timeout", githubYAMLString("${{ inputs.timeout }}"))
		}},
		{name: "timeout ceiling", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(job, "with"), "timeout", &yamlv3.Node{Kind: yamlv3.ScalarNode, Tag: "!!int", Value: "361"})
		}},
		{name: "inherited secrets", mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "secrets", githubYAMLString("inherit")) }},
		{name: "caller permission", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(job, "permissions", githubYAMLMap("id-token", githubYAMLString("write")))
		}},
		{name: "caller environment", mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "environment", githubYAMLString("nkd-release")) }},
		{name: "remote reference", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(job, "uses", githubYAMLString("other/repo/.github/workflows/execute.yml@main"))
		}},
		{name: "unknown input", mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(job, "with"), "runner", githubYAMLString("self-hosted"))
		}},
		{name: "duplicate input", mutate: func(job *yamlv3.Node) {
			with := githubYAMLField(job, "with")
			with.Content = append(with.Content, githubYAMLString("stage"), githubYAMLString("first"))
		}},
		{name: "child condition", child: true, mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "if", githubYAMLString("${{ false }}")) }},
		{name: "child dependency", child: true, mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "needs", githubYAMLString("another")) }},
		{name: "child outputs", child: true, mutate: func(job *yamlv3.Node) {
			githubYAMLSet(job, "outputs", githubYAMLMap("result", githubYAMLString("success")))
		}},
		{name: "child environment", child: true, mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "environment", githubYAMLString("nkd-release")) }},
		{name: "child permission", child: true, mutate: func(job *yamlv3.Node) {
			githubYAMLSet(job, "permissions", githubYAMLMap("id-token", githubYAMLString("write")))
		}},
		{name: "child matrix", child: true, mutate: func(job *yamlv3.Node) { githubYAMLSet(job, "strategy", githubYAMLMap("matrix", githubYAMLMap())) }},
		{name: "child literal timeout", child: true, mutate: func(job *yamlv3.Node) {
			githubYAMLSet(job, "timeout-minutes", &yamlv3.Node{Kind: yamlv3.ScalarNode, Tag: "!!int", Value: "60"})
		}},
		{name: "child selector", child: true, mutate: func(job *yamlv3.Node) {
			githubYAMLSet(githubYAMLField(githubYAMLField(job, "steps").Content[2], "with"), "action", githubYAMLString("${{ github.job }}"))
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			changedFiles := maps.Clone(files)
			changed := raw
			selected := raw
			id := "first"
			if test.child {
				selected, id = files[childPath], "execute"
			}
			document, jobs, err := githubReusableDocument(selected)
			if err != nil {
				t.Fatal(err)
			}
			test.mutate(githubYAMLField(jobs, id))
			if test.child {
				changedFiles[childPath] = githubReusableBytes(t, document)
			} else {
				changed = githubReusableBytes(t, document)
			}
			_, err = expandGitHubReusableWorkflows(t.Context(), plan, changed, changedFiles)
			assertFactoryErrorCode(t, err, e.CodeEngineCapability)
		})
	}
	for _, test := range []struct {
		name string
		edit func(map[string][]byte)
		code e.Code
	}{
		{name: "missing child", code: e.CodePipelineDrift, edit: func(files map[string][]byte) { delete(files, childPath) }},
		{name: "extra child job", code: e.CodeEngineCapability, edit: func(files map[string][]byte) {
			document, jobs, err := githubReusableDocument(files[childPath])
			if err != nil {
				t.Fatal(err)
			}
			githubYAMLSet(jobs, "extra", githubYAMLMap("runs-on", githubYAMLString("ubuntu-24.04")))
			files[childPath] = githubReusableBytes(t, document)
		}},
		{name: "root permission", code: e.CodeEngineCapability, edit: func(files map[string][]byte) {
			document, _, err := githubReusableDocument(files[childPath])
			if err != nil {
				t.Fatal(err)
			}
			githubYAMLSet(githubYAMLField(document.Content[0], "permissions"), "id-token", githubYAMLString("write"))
			files[childPath] = githubReusableBytes(t, document)
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			changed := maps.Clone(files)
			test.edit(changed)
			_, err := expandGitHubReusableWorkflows(t.Context(), plan, raw, changed)
			assertFactoryErrorCode(t, err, test.code)
		})
	}
}

func TestGitHubReusableTemplatePathsAreStableAcrossMembership(t *testing.T) {
	plan, actions, root := githubReusableFixture(t)
	before := map[string][]byte{}
	_, err := lowerGitHubReusableWorkflows(plan, githubReusableBytes(t, root), before, actions)
	if err != nil {
		t.Fatal(err)
	}
	jobs := githubYAMLField(root, "jobs")
	additional, err := githubResolveAliases(githubYAMLField(jobs, "first"), map[*yamlv3.Node]bool{})
	if err != nil {
		t.Fatal(err)
	}
	githubYAMLSet(additional, "name", githubYAMLString("Independent additional output"))
	githubYAMLSet(jobs, "new-output", additional)
	after := map[string][]byte{}
	_, err = lowerGitHubReusableWorkflows(plan, githubReusableBytes(t, root), after, actions)
	if err != nil {
		t.Fatal(err)
	}
	if !maps.EqualFunc(before, after, bytes.Equal) {
		t.Fatal("adding an independent output changed reusable template paths or bytes")
	}
}


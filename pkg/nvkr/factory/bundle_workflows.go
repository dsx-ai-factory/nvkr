func preflightNewGeneratedWorkflowOwner(ctx context.Context, root string, bundle *GeneratedBundle) error {
	lease, err := generatedDestination(root, bundle.ManifestPath+".lease")
	if err != nil {
		return err
	}
	_, err = os.Lstat(lease)
	if err == nil {
		// An existing writer may have published payloads ahead of its manifest.
		// Wait on the persistent lease before inspecting that intermediate state.
		return nil
	}
	if !errors.Is(err, os.ErrNotExist) {
		return e.Wrap(e.CodePipelineDrift, err, "inspecting generated workflow owner")
	}
	if err := preflightGeneratedWorkflowClaims(ctx, root, bundle); err != nil {
		// A first writer may have acquired its lease during this read-only pass.
		// Its eventual manifest must be inspected under the lock before refusing.
		if _, leaseErr := os.Lstat(lease); leaseErr == nil {
			return nil
		}
		return err
	}
	return nil
}

// A newly reserved child name cannot replace an operator-owned workflow. Exact
// regenerated bytes are accepted for recovery after payload publication but
// before the first owning manifest. Existing owned members retain repair behavior.
func preflightGeneratedWorkflowClaims(ctx context.Context, root string, bundle *GeneratedBundle) error {
	prior, err := priorGeneratedMembers(ctx, root, bundle)
	if err != nil {
		return err
	}
	owned := make(map[string]bool, len(prior))
	union := *bundle
	union.Files = make(map[string][]byte, len(bundle.Files)+len(prior))
	for name, raw := range bundle.Files {
		union.Files[name] = raw
	}
	for _, member := range prior {
		owned[member.Path] = true
		union.Files[member.Path] = nil
	}
	if err := checkGeneratedWorkflowContents(ctx, root, &union); err != nil {
		return err
	}
	for _, name := range sortedFileNames(bundle.Files) {
		if !IsGeneratedGitHubChildWorkflowPath(name) || owned[name] {
			continue
		}
		if err := ctx.Err(); err != nil {
			return e.Wrap(e.CodeTimeout, err, "generated workflow ownership check canceled")
		}
		destination, err := generatedDestination(root, name)
		if err != nil {
			return err
		}
		info, err := os.Lstat(destination)
		if errors.Is(err, os.ErrNotExist) {
			continue
		}
		if err != nil || !info.Mode().IsRegular() || info.Mode().Perm() != 0o644 {
			return e.New(e.CodeWriteConflict, "new generated workflow %s is unsafe or unowned", name)
		}
		raw, err := readGeneratedContext(ctx, destination)
		if err != nil || !bytes.Equal(raw, bundle.Files[name]) {
			return e.New(e.CodeWriteConflict, "new generated workflow %s is unowned or modified", name)
		}
	}
	return nil
}

// Only this owner's reserved sibling names participate in the finite inventory.
// Other producer namespaces and operator-authored workflows remain independent.
func checkGeneratedWorkflowContents(ctx context.Context, root string, bundle *GeneratedBundle) error {
	const relative = ".github/workflows"
	directory, err := generatedDestination(root, relative)
	if err != nil {
		return err
	}
	before, err := os.Lstat(directory)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil || !before.IsDir() || before.Mode()&os.ModeSymlink != 0 {
		return e.New(e.CodePipelineDrift, "generated workflow directory is unsafe")
	}
	if err := validateGeneratedDirectoryChain(root, relative); err != nil {
		return e.Wrap(e.CodePipelineDrift, err, "generated workflow directory has unsafe parents")
	}
	opened, err := os.Open(directory)
	if err != nil {
		return e.Wrap(e.CodePipelineDrift, err, "opening generated workflow directory")
	}
	defer func() { _ = opened.Close() }()
	info, err := opened.Stat()
	if err != nil || !os.SameFile(before, info) {
		return e.New(e.CodePipelineDrift, "generated workflow directory changed while opening")
	}
	seen := 0
	for {
		if err := ctx.Err(); err != nil {
			return e.Wrap(e.CodeTimeout, err, "generated workflow inventory canceled")
		}
		entries, readErr := opened.ReadDir(128)
		for _, entry := range entries {
			seen++
			if seen > maxGeneratedDirEntries {
				return e.New(e.CodePipelineDrift, "workflow directory exceeds %d entries", maxGeneratedDirEntries)
			}
			member := relative + "/" + entry.Name()
			owner, reserved := githubChildWorkflowOwner(member)
			if !reserved || owner != bundle.WorkflowPath {
				continue
			}
			if _, allowed := bundle.Files[member]; !allowed {
				return e.New(e.CodePipelineDrift, "unexpected generated workflow %s", member)
			}
			info, err := os.Lstat(filepath.Join(directory, entry.Name()))
			if err != nil || !info.Mode().IsRegular() {
				return e.New(e.CodePipelineDrift, "generated workflow %s is unsafe", member)
			}
		}
		if errors.Is(readErr, io.EOF) {
			break
		}
		if readErr != nil {
			return e.Wrap(e.CodePipelineDrift, readErr, "listing generated workflow directory")
		}
	}
	after, err := os.Lstat(directory)
	if err != nil || !after.IsDir() || after.Mode()&os.ModeSymlink != 0 || !os.SameFile(before, after) {
		return e.New(e.CodePipelineDrift, "generated workflow directory changed during inspection")
	}
	return nil
}

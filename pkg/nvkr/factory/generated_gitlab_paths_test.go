// This fixture tests storage ownership only. It grants no executable Plan or
// provider authority and is not evidence of GitLab runtime acceptance.
func gitlabStorageBundle() *GeneratedBundle {
	workflow := []byte("nvkr-test:\n  script: ['true']\n")
	return &GeneratedBundle{Engine: EngineGitLab, WorkflowPath: GitLabWorkflowPath,
		ManifestPath: GitLabManifestPath, PlanPath: GitLabPlanPath,
		PlanDigest:     pipeline.FileDigest([]byte("storage fixture")),
		WorkflowDigest: pipeline.FileDigest(workflow),
		Files:          map[string][]byte{GitLabWorkflowPath: workflow, GitLabPlanPath: []byte("{}")}}
}

func TestGitLabStorageCoexistsWithOperatorAndGitHubFiles(t *testing.T) {
	root := t.TempDir()
	operator := filepath.Join(root, ".gitlab-ci.yml")
	want := []byte("include:\n  - local: .gitlab/nvkr-run/pipeline.yml\n")
	if err := os.WriteFile(operator, want, 0o644); err != nil {
		t.Fatal(err)
	}
	// An unrelated GitHub tree must not be inventoried or followed by GitLab.
	if err := os.Symlink(t.TempDir(), filepath.Join(root, ".github")); err != nil {
		t.Fatal(err)
	}
	bundle := gitlabStorageBundle()
	for range 2 {
		if err := WriteGeneratedBundle(t.Context(), root, bundle); err != nil {
			t.Fatal(err)
		}
		if err := CheckGeneratedBundle(t.Context(), root, bundle); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(operator)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("operator root changed: %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, GitLabWorkflowPath), []byte("operator edit"), 0o644); err != nil {
		t.Fatal(err)
	}
	assertFactoryErrorCode(t, CheckGeneratedBundle(t.Context(), root, bundle), e.CodePipelineDrift)
}

func TestGitLabStorageRefusesEscapedAndCrossProviderMembers(t *testing.T) {
	raw := []byte(`{"fixture":"cross-provider"}`)
	sharedMember, err := namedPlanStorePath("plan/cross-provider", raw, ".json")
	if err != nil {
		t.Fatal(err)
	}
	for _, member := range []string{".gitlab-ci.yml", GitHubWorkflowPath, sharedMember, ".gitlab/nvkr-run-other/plan.json", GitLabManifestPath, GitLabManifestPath + ".lease", ".gitlab/nvkr-run/../outside.json"} {
		t.Run(member, func(t *testing.T) {
			bundle := gitlabStorageBundle()
			bundle.Files[member] = raw
			_, _, err := ManifestFor(bundle)
			assertFactoryErrorCode(t, err, e.CodeInvalidCatalog)
			root := t.TempDir()
			assertFactoryErrorCode(t, WriteGeneratedBundle(t.Context(), root, bundle), e.CodeInvalidCatalog)
			entries, err := os.ReadDir(root)
			if err != nil || len(entries) != 0 {
				t.Fatalf("rejected cross-provider member produced output: %v", err)
			}
		})
	}
	for _, engine := range []string{EngineGitHub, EngineGitLab} {
		t.Run(engine, func(t *testing.T) {
			bundle := gitlabStorageBundle()
			if engine == EngineGitHub {
				bundle.Engine = EngineGitHub
			} else {
				bundle.WorkflowPath = GitHubWorkflowPath
			}
			_, _, err := ManifestFor(bundle)
			assertFactoryErrorCode(t, err, e.CodeInvalidCatalog)
		})
	}
}

func TestGitLabStorageRetiresOnlyOwnedUnmodifiedMembers(t *testing.T) {
	for _, modified := range []bool{false, true} {
		t.Run(map[bool]string{false: "unchanged", true: "modified"}[modified], func(t *testing.T) {
			root := t.TempDir()
			prior := gitlabStorageBundle()
			const obsolete = ".gitlab/nvkr-run/old.json"
			prior.Files[obsolete] = []byte("old generated bytes")
			if err := WriteGeneratedBundle(t.Context(), root, prior); err != nil {
				t.Fatal(err)
			}
			if modified {
				if err := os.WriteFile(filepath.Join(root, obsolete), []byte("operator bytes"), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			err := WriteGeneratedBundle(t.Context(), root, gitlabStorageBundle())
			if modified {
				assertFactoryErrorCode(t, err, e.CodePipelineDrift)
				got, readErr := os.ReadFile(filepath.Join(root, obsolete))
				if readErr != nil || string(got) != "operator bytes" {
					t.Fatal("modified member was retired")
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(filepath.Join(root, obsolete)); !os.IsNotExist(err) {
				t.Fatal("owned obsolete member survived")
			}
		})
	}
}

func TestGitLabStorageRefusesSymlinkParents(t *testing.T) {
	for _, parent := range []string{".gitlab", ".gitlab/nvkr-run"} {
		t.Run(parent, func(t *testing.T) {
			root := t.TempDir()
			external := t.TempDir()
			if err := os.MkdirAll(filepath.Dir(filepath.Join(root, parent)), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.Symlink(external, filepath.Join(root, parent)); err != nil {
				t.Fatal(err)
			}
			if err := WriteGeneratedBundle(t.Context(), root, gitlabStorageBundle()); err == nil {
				t.Fatal("write followed symlink parent")
			}
			if err := CheckGeneratedBundle(t.Context(), root, gitlabStorageBundle()); err == nil {
				t.Fatal("check followed symlink parent")
			}
			entries, err := os.ReadDir(external)
			if err != nil || len(entries) != 0 {
				t.Fatal("rejected write changed external directory")
			}
		})
	}
}

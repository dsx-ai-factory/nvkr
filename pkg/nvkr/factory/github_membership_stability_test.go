// Exercise the real compiler/renderer boundary: a new independent output may
// add jobs and change Run accounting, but cannot reschedule existing outputs.
func TestGitHubUnrelatedOutputPreservesExistingJobs(t *testing.T) {
	for _, fixture := range []struct {
		name string
		plan func(*testing.T) *Plan
	}{
		{name: "binary", plan: func(t *testing.T) *Plan { return buildTransportPlan(t, "binary") }},
		{name: "native binary", plan: func(t *testing.T) *Plan {
			return recompileGitHubStabilityPlan(t, buildTransportPlan(t, "binary"), func(inputs *githubStabilityInputs) {
				inputs.environment.RunsOn = ""
				inputs.environment.GitHubRunners = map[string]string{"linux/amd64": "ubuntu-24.04", "linux/arm64": "ubuntu-24.04-arm"}
			})
		}},
		{name: "collected native binary", plan: func(t *testing.T) *Plan {
			return recompileGitHubStabilityPlan(t, buildTransportPlan(t, "binary"), func(inputs *githubStabilityInputs) {
				inputs.environment.RunsOn = ""
				inputs.environment.GitHubRunners = map[string]string{"linux/amd64": "ubuntu-24.04", "linux/arm64": "ubuntu-24.04-arm"}
				inputs.definition.Outputs[0].Name = "bravo"
				// Cross the direct-result limit even after shared source work and
				// Verify/SBOM pairing reduce the number of provider jobs.
				for index := 1; index < 32; index++ {
					output := inputs.definition.Outputs[0]
					output.Name = fmt.Sprintf("omega-%02d", index)
					inputs.definition.Outputs = append(inputs.definition.Outputs, output)
				}
			})
		}},
		{name: "source", plan: func(t *testing.T) *Plan { return buildTransportPlan(t, "source") }},
		{name: "per-output publication", plan: func(t *testing.T) *Plan {
			return recompileGitHubStabilityPlan(t, signedTestPlan(t, cosignSigningProfile(), ghcrTarget()), func(inputs *githubStabilityInputs) {
				inputs.definition.Outputs[0].Components = []string{"containerd"}
				inputs.environment.Publication.Mode = "per-output-v1"
				inputs.environment.Publication.CredentialRef = "github:GITHUB_TOKEN"
			})
		}},
	} {
		for _, addedName := range []string{"alpha", "middle", "zulu"} {
			t.Run(fixture.name+"/"+addedName, func(t *testing.T) {
				beforePlan := recompileGitHubStabilityPlan(t, fixture.plan(t), func(inputs *githubStabilityInputs) {
					inputs.definition.Outputs[0].Name = "bravo"
					other := inputs.definition.Outputs[0]
					other.Name = "tango"
					inputs.definition.Outputs = append(inputs.definition.Outputs, other)
				})
				afterPlan := recompileGitHubStabilityPlan(t, beforePlan, func(inputs *githubStabilityInputs) {
					output := inputs.definition.Outputs[0]
					output.Name = addedName
					inputs.definition.Outputs = append(inputs.definition.Outputs, output)
					slices.SortFunc(inputs.definition.Outputs, func(a, b authored.DefinitionOutput) int { return strings.Compare(a.Name, b.Name) })
				})
				if fixture.name == "collected native binary" {
					projection, err := githubNeedsForPlan(t.Context(), beforePlan)
					if err != nil {
						t.Fatal(err)
					}
					if len(projection.Collectors) == 0 {
						t.Fatalf("large fixture must exercise stable collector membership; got %d original jobs", len(projection.Full[githubFinalizerJobID]))
					}
					t.Logf("collector fixture: %d original jobs in %d fixed buckets", len(projection.Full[githubFinalizerJobID]), len(projection.Collectors))
				}
				before, err := RenderGitHub(t.Context(), beforePlan)
				if err != nil {
					t.Fatal(err)
				}
				after, err := RenderGitHub(t.Context(), afterPlan)
				if err != nil {
					t.Fatal(err)
				}
				assertGitHubExistingOutputJobs(t, beforePlan, afterPlan, before, after)
				// Removing the added output restores every generated byte, including
				// alias placement, parameter data, exact Plan and bundle identities.
				restoredPlan := recompileGitHubStabilityPlan(t, afterPlan, func(inputs *githubStabilityInputs) {
					inputs.definition.Outputs = slices.DeleteFunc(inputs.definition.Outputs, func(output authored.DefinitionOutput) bool {
						return output.Name == addedName
					})
				})
				restored, err := RenderGitHub(t.Context(), restoredPlan)
				if err != nil {
					t.Fatal(err)
				}
				if !reflect.DeepEqual(before, restored) {
					t.Error("removing the added output did not restore the exact original generated bundle")
				}
			})
		}
	}
}

func assertGitHubExistingOutputJobs(t *testing.T, beforePlan, afterPlan *Plan, before, after *GeneratedBundle) {
	t.Helper()
	_, beforeJobs, err := githubStages(beforePlan)
	if err != nil {
		t.Fatal(err)
	}
	_, afterJobs, err := githubStages(afterPlan)
	if err != nil {
		t.Fatal(err)
	}
	globalJobs := map[string]bool{"nvkr-lifecycle-run": true}
	beforeProjection, err := githubNeedsForPlan(t.Context(), beforePlan)
	if err != nil {
		t.Fatal(err)
	}
	afterProjection, err := githubNeedsForPlan(t.Context(), afterPlan)
	if err != nil {
		t.Fatal(err)
	}
	for id, members := range beforeProjection.Collectors {
		globalJobs[id] = true
		for _, member := range members {
			if !slices.Contains(afterProjection.Collectors[id], member) {
				t.Errorf("unrelated output moved existing finalizer member %s out of %s", member, id)
			}
		}
	}
	for id, needs := range beforeProjection.Reduced {
		if _, collector := beforeProjection.Collectors[id]; collector || id == githubFinalizerJobID {
			continue
		}
		// Aggregate release assembly is exempted with its node kind below.
		if slices.Equal(needs, afterProjection.Reduced[id]) {
			continue
		}
		aggregate := false
		for _, node := range beforePlan.Graph.Nodes {
			aggregate = aggregate || node.Kind == NodeAssembleRelease && beforeJobs[node.ID] == id
		}
		if !aggregate {
			t.Errorf("unrelated output changed emitted prerequisites for %s", id)
		}
	}
	for _, node := range beforePlan.Graph.Nodes {
		if beforeJobs[node.ID] != afterJobs[node.ID] {
			t.Errorf("unrelated output changed job for %s: %s -> %s", node.ID, beforeJobs[node.ID], afterJobs[node.ID])
		}
		if node.Kind == NodeAssembleRelease {
			// Only release assembly and Run finalization consume the complete
			// output set. Every existing per-output publication job stays equal.
			globalJobs[beforeJobs[node.ID]] = true
		}
	}
	// Inspect mapping keys in their serialized order. Map decoding below checks
	// job semantics but would conceal unrelated jobs moving around the workflow.
	beforeOrder := slices.DeleteFunc(githubSerializedJobOrder(t, before.Files[before.WorkflowPath]), func(id string) bool {
		return globalJobs[id]
	})
	retained := make(map[string]bool, len(beforeOrder))
	for _, id := range beforeOrder {
		retained[id] = true
	}
	afterOrder := slices.DeleteFunc(githubSerializedJobOrder(t, after.Files[after.WorkflowPath]), func(id string) bool {
		return !retained[id]
	})
	if !slices.Equal(beforeOrder, afterOrder) {
		t.Errorf("unrelated output changed existing job emission order: %v -> %v", beforeOrder, afterOrder)
	}
	for _, projection := range []struct {
		name          string
		before, after []byte
	}{
		// Decoding resolves aliases, whose definition site may move when a
		// newly inserted job is the first user of an existing shared sequence.
		{name: "shared", before: logicalGitHubWorkflow(t, beforePlan, before.Files[before.WorkflowPath]), after: logicalGitHubWorkflow(t, afterPlan, after.Files[after.WorkflowPath])},
		{name: "expanded", before: expandedGitHubWorkflow(t, before), after: expandedGitHubWorkflow(t, after)},
	} {
		beforeWorkflow := decodeGitHubWorkflow(t, projection.before)
		afterWorkflow := decodeGitHubWorkflow(t, projection.after)
		if len(afterWorkflow.Jobs) <= len(beforeWorkflow.Jobs) {
			t.Fatal("adding an independent output did not add its own provider jobs")
		}
		for id, job := range beforeWorkflow.Jobs {
			if globalJobs[id] {
				continue
			}
			for index, step := range job.Steps {
				if step.ID == githubRunStartSummaryID {
					job.Steps[index] = githubRunStartSummary(afterPlan)
				}
			}
			if !reflect.DeepEqual(job, afterWorkflow.Jobs[id]) {
				t.Errorf("unrelated output changed existing %s workflow job %s", projection.name, id)
			}
		}
	}
	beforeData, afterData := sharedGitHubActionData(t, before), sharedGitHubActionData(t, after)
	for id, entry := range beforeData.Entries {
		if !globalJobs[id] && !reflect.DeepEqual(entry, afterData.Entries[id]) {
			t.Errorf("unrelated output changed invocation parameters for job %s", id)
		}
	}
	for name, raw := range before.Files {
		if strings.HasPrefix(name, githubActionsDirectory) && !bytes.Equal(raw, after.Files[name]) {
			t.Errorf("unrelated output changed existing execution template %s", name)
		}
	}
}

func githubSerializedJobOrder(t *testing.T, raw []byte) []string {
	t.Helper()
	var document yamlv3.Node
	if err := yamlv3.Unmarshal(raw, &document); err != nil {
		t.Fatal(err)
	}
	jobs := githubTestYAMLField(t, document.Content[0], "jobs")
	var order []string
	for index := 0; index < len(jobs.Content); index += 2 {
		order = append(order, jobs.Content[index].Value)
	}
	return order
}
